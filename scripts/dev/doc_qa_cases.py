"""Write domovoi/doc_qa/shared_cases.json: the vectors both places are held to.

    python scripts/dev/doc_qa_cases.py          # rewrite the file from the Python rules
    python scripts/dev/doc_qa_cases.py --check  # exit 1 if the file is out of date

The inputs are written here by hand; the expected outputs are what the
Python implementation (domovoi/doc_qa) gives. The server's tests
(domovoi/tests/test_doc_qa.py) and the app's (DocQaSharedCasesTest.kt)
both read the file, so a rule changed on one side fails the other's tests
until it changes there too.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from domovoi.doc_qa import answer, bm25, notes, text  # noqa: E402

OUT = ROOT / "domovoi" / "doc_qa" / "shared_cases.json"

LEASE = [
    {"label": "page header", "text": "Residential Lease - 12 Elm Street"},
    {"label": "p. 1", "text": "This lease is between Alex Rivera (the landlord) and Sam Lee (the tenant). "
                              "The term starts on 1 March 2026 and runs for twelve months."},
    {"label": "p. 2", "text": "The monthly rent is $1,200, due on the first day of each month. "
                              "A late fee of $50 applies when rent is more than five days late. "
                              "Rent is paid by bank transfer."},
    {"label": "p. 3", "text": "The security deposit is $1,500. It is returned within 30 days after the "
                              "tenant moves out, less the cost of any damage beyond normal wear."},
    {"label": "p. 4", "text": "Pets are not allowed without written permission from the landlord. "
                              "Smoking is not allowed anywhere in the building."},
]
SHEET = [
    {"label": "Sheet Budget, rows 2-4", "head": "| Item | Amount |\n|---|---|",
     "text": "| Rent | 1200 |\n| Power | 85.50 |\n| Water | 40 |"},
    {"label": "Sheet Budget, column totals",
     "text": "Column totals for sheet Budget, worked out by Domovoi from rows 2-4:\n"
             "Amount: total 1,325.50, average 441.83, lowest 40, highest 1,200 (3 numbers)"},
]
LONG = [{"label": f"para {i}", "text": ("Sentence number %d talks about the garden. " % i) * 12}
        for i in range(1, 4)]


def given_dicts(given):
    return [{"cite": g.cite, "score": round(g.score, 4)} for g in given]


def main() -> int:
    cases: dict = {"about": "Generated by scripts/dev/doc_qa_cases.py from domovoi/doc_qa; read by "
                            "domovoi/tests/test_doc_qa.py and the app's DocQaSharedCasesTest.kt.",
                   "constants": {"passage_chars": text.PASSAGE_CHARS, "top_k": answer.TOP_K,
                                 "retrieve_chars": answer.RETRIEVE_CHARS,
                                 "single_pass_chars": answer.SINGLE_PASS_CHARS,
                                 "not_found": answer.NOT_FOUND,
                                 "note_uncited": answer.NOTE_UNCITED, "note_quote": answer.NOTE_QUOTE,
                                 "rules_question": answer.RULES_QUESTION,
                                 "rules_summary": answer.RULES_SUMMARY,
                                 "stop_words": sorted(text.STOP_WORDS)}}
    tok_in = [
        "The tenants are leasing; leases, leased, LEASE!",
        "Paid $1,200.50 on 3/4 at 10:30.",
        "Coffee ﬁle ＡＢＣ naïve café",
        "Stopped stopping, running quickly; studies, classes, bus, this",
        "What's the pet policy?",
        "e-mail x_y 2nd 1.5.",
    ]
    cases["tokens"] = [{"in": s, "words": text.words(s), "tokens": text.tokens(s)} for s in tok_in]
    sent_in = [
        "Rent is due on the 1st. Late fees apply e.g. after 5 days. The fee is $1.50 each. \"Quoted\" here.\nNext line",
        "One!  Two? three. Four",
        "| a | b |\n| 1 | 2 |",
        "x" * 2000 + " tail",
    ]
    cases["sentences"] = [{"in": s, "out": text.sentences(s)} for s in sent_in]
    cases["passages"] = []
    for parts, target in ((LEASE, 120), (LEASE, text.PASSAGE_CHARS), (SHEET, 60), (LONG, 300)):
        ps = text.cut_passages(parts, target=target)
        cases["passages"].append({"parts": parts, "target": target,
                                  "out": [{"label": p.label, "part": p.part, "text": p.text, "head": p.head}
                                          for p in ps]})
    cases["bm25"] = []
    for parts, q in ((LEASE, "How much is the security deposit?"), (LEASE, "late rent fee"),
                     (SHEET, "total amount"), (LEASE, "unicorns")):
        ps = text.cut_passages(parts)
        cases["bm25"].append({"parts": parts, "query": q, "terms": answer.search_query(q),
                              "scores": [round(s, 4) for s in bm25.scores(ps, answer.search_query(q))]})
    two = [{"name": "lease.pdf", "parts": LEASE}, {"name": "budget.xlsx", "parts": SHEET}]
    cases["retrieve"] = []
    for docs, q, prev, budget in (
        ([two[0]], "How much is the deposit?", None, answer.RETRIEVE_CHARS),
        ([two[0]], "and the late fee?", "How much is the rent?", answer.RETRIEVE_CHARS),
        ([two[0]], "Can I keep a cat?", None, answer.RETRIEVE_CHARS),
        ([two[0]], "rent", None, 150),
        (two, "what is the rent amount", None, answer.RETRIEVE_CHARS),
        ([two[0]], "Who won the 1998 World Cup?", None, answer.RETRIEVE_CHARS),
        ([two[0]], "Who won the 1998 World Cup?", "How much is the rent?", answer.RETRIEVE_CHARS),
        ([two[0]], "what about pets?", "Is smoking allowed?", answer.RETRIEVE_CHARS),
    ):
        mode = answer.choose_mode(q)
        g = answer.retrieve(docs, q, prev, mode=mode, budget=budget)
        cases["retrieve"].append({"docs": docs, "question": q, "previous": prev, "budget": budget,
                                  "mode": mode, "out": given_dicts(g)})
    cases["summary_retrieve"] = []
    for docs, limit in (([two[0]], answer.SINGLE_PASS_CHARS), ([two[0]], 200)):
        g = answer.retrieve(docs, "summarize this", mode="summary", single_pass=limit)
        cases["summary_retrieve"].append({"docs": docs, "single_pass": limit, "out": [x.cite for x in g]})
    cases["follow_up"] = [{"in": s, "out": answer.is_follow_up(s)} for s in (
        "and the deposit?", "And how much is it?", "what about pets?", "How about the fee", "is it refundable?",
        "Who won the 1998 World Cup?", "When is the rent due?", "Does that include water and power bills?", "")]
    cases["mode"] = [{"in": s, "out": answer.choose_mode(s)} for s in (
        "Summarize this please", "Can you summarise it?", "give me an overview", "What's this about?",
        "what’s this about", "key points?", "TL;DR", "tldr pls", "What is the rent?", "sum it up",
        "Is there a summary of fees?", "how many pets")]
    cases["prompt"] = []
    for docs, q, prev in (([two[0]], "How much is the deposit?", None),
                          ([two[0]], "and the late fee?", "How much is the rent?"),
                          (two, "rent amount", None)):
        g = answer.retrieve(docs, q, prev)
        pr = answer.build_prompt(q, g, [d["name"] for d in docs], previous=prev)
        cases["prompt"].append({"docs": docs, "question": q, "previous": prev, "mode": "question",
                                "user": pr["user"], "rules": "question"})
    g = answer.retrieve([two[0]], "summarize", mode="summary")
    pr = answer.build_prompt("summarize", g, ["lease.pdf"], mode="summary")
    cases["prompt"].append({"docs": [two[0]], "question": "summarize", "previous": None, "mode": "summary",
                            "user": pr["user"], "rules": "summary"})
    cases["check"] = []
    replies = [
        ([two[0]], "How much is the deposit?",
         "The deposit is $1,500 [p. 3]. It comes back within 30 days [p. 9] (page 3)."),
        ([two[0]], "How much is the deposit?", "I could not find that in the document."),
        ([two[0]], "How much is the deposit?", "The deposit is $1,500."),
        ([two[0]], "How much is the deposit?",
         'The lease says "the deposit is returned within ninety days" [p. 3].'),
        ([two[0]], "How much is the deposit?",
         'It says "returned within 30 days after the tenant moves out" [p. 3; p. 12].'),
        ([two[0]], "Can I keep a cat?", "The passages don't mention cats."),
        (two, "what is the rent amount", "Rent is $1,200 [lease.pdf, p. 2] and the sheet lists 1200 [Sheet Budget, rows 2-4]."),
        (two, "what is the rent amount", "Rent is $1,200 [p. 2]."),
        ([two[0]], "How much is the deposit?", "See [sic] the [x] box. The deposit is $1,500 [Page 3]."),
        ([two[0]], "How much is the deposit?", "Deposit: $1,500 [source: p.3]. Also see [the lease](http://example.com)."),
        ([two[0]], "How much is the deposit?", ""),
    ]
    for docs, q, reply in replies:
        g = answer.retrieve(docs, q)
        c = answer.check_reply(reply, g, q, [d["name"] for d in docs])
        cases["check"].append({"docs": docs, "question": q, "reply": reply,
                               "given": [x.cite for x in g],
                               "out": {"content": c.content, "found": c.found, "cited": c.cited,
                                       "dropped": c.dropped, "unverified_quotes": c.unverified_quotes,
                                       "notes": c.notes,
                                       "sources": [{"label": s["label"], "cited": s["cited"], "match": s["match"]}
                                                   for s in c.sources]}})
    cases["labels"] = [{"in": s, "out": answer.norm_label(s)} for s in (
        "Page 7", "p.7", "pg. 12", "P 3", "Source: p. 2.", "Sheet Budget, rows 2-41", "Section:  Deposit (para 3)",
        "see p. 4", "pp. 5")]
    cases["notes"] = {
        "pages_phrase": [{"in": p, "out": notes.pages_phrase(p)} for p in ([3], [3, 7], [3, 7, 9], list(range(1, 13)))],
        "scanned": [{"in": p, "out": notes.scanned_note(p)} for p in ([2], [2, 5])],
        "garbled": [{"in": p, "out": notes.garbled_note(p)} for p in ([1], [1, 4])],
        "formulas": [{"in": n, "out": notes.formulas_note(n)} for n in (1, 16, 1200)],
        "long": [{"in": n, "out": notes.long_note(n)} for n in (9764, 999, 12345)],
        "not_found": [{"in": n, "out": answer.note_not_found(n)} for n in (["lease.pdf"], ["a.pdf", "b.docx"], [], ["a", "b", "c"])],
        "summary_too_long": [{"names": ["lease.pdf"], "words": 9764,
                              "out": answer.summary_too_long_text(["lease.pdf"], 9764)}],
        "summary_line": [{"in": a, "out": notes.summary_line(*a)} for a in (
            ["lease.pdf", "pdf", 30, 9764], ["lease.pdf", "pdf", 1, 1], ["budget.xlsx", "xlsx", None, 120, 2],
            ["notes.txt", "txt", None, 999])],
    }
    data = json.dumps(cases, indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        if OUT.read_text(encoding="utf-8") != data:
            print(f"{OUT} is out of date: run scripts/dev/doc_qa_cases.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_bytes(data.encode("utf-8"))
    print(f"wrote {OUT} ({len(data):,} chars)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
