#!/usr/bin/env python3
"""Writes the licence notice for every crate in libdomovoi_tor.so.

    python3 native/domovoi-tor/third_party_licences.py [--target aarch64-linux-android] [OUT]

Reads `cargo metadata` (the crate graph Cargo.lock pins, for the target)
and each crate's own LICENSE / COPYING / NOTICE / UNLICENSE files from
Cargo's source cache (run a build first, so the sources are there). Each
distinct licence text is written once, with every crate that carries it
listed above it, so the notice holds every copyright line the crates ship.
OUT defaults to android/licences/domovoi-tor/THIRD-PARTY-LICENSES.txt, which
the Android app carries in its licences card; android/licences/SHA256SUMS
lists it. Standard library only.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAMES = re.compile(r"^(licen[cs]e|copying|notice|unlicense|copyright)([._-].*)?$", re.I)


def main(argv: list[str]) -> int:
    target = "aarch64-linux-android"
    if "--target" in argv:
        i = argv.index("--target")
        target = argv[i + 1]
        del argv[i:i + 2]
    out = Path(argv[0]) if argv else HERE.parent.parent / "android/licences/domovoi-tor/THIRD-PARTY-LICENSES.txt"
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        cwd=HERE, check=True, capture_output=True, text=True).stdout)
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    pkgs = {p["id"]: p for p in meta["packages"]}
    root = meta["resolve"]["root"]
    seen: set[str] = set()
    todo = [root]
    while todo:
        i = todo.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
                todo.append(d["pkg"])
    seen.discard(root)
    texts: dict[str, list[str]] = defaultdict(list)
    missing = []
    rows = []
    for i in sorted(seen, key=lambda i: (pkgs[i]["name"], pkgs[i]["version"])):
        p = pkgs[i]
        crate = f'{p["name"]} {p["version"]}'
        rows.append(f'{crate:48} {p.get("license") or p.get("license_file") or "?"}')
        folder = Path(p["manifest_path"]).parent
        files = sorted(f for f in folder.iterdir() if f.is_file() and NAMES.match(f.name))
        if not files:
            missing.append(crate)
        for f in files:
            body = f.read_text(encoding="utf-8", errors="replace").strip()
            texts[body].append(f"{crate}: {f.name}")
    lines = [
        "Away chat's Tor (libdomovoi_tor.so): Arti and the crates built into it.",
        "Generated by native/domovoi-tor/third_party_licences.py from Cargo.lock.",
        "",
        f"{len(rows)} crates (licence as each crate declares it):",
        "",
        *rows,
        "",
    ]
    if missing:
        lines += ["Crates that ship no licence file of their own (their declared licence above applies):",
                  "", *missing, ""]
    for body, users in sorted(texts.items(), key=lambda kv: kv[1][0]):
        lines += ["=" * 78, *users, "-" * 78, body, ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{out}: {len(rows)} crates, {len(texts)} distinct texts, {len(missing)} without a file")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
