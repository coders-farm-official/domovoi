"""scripts/release/sbom.py: the release's SBOMs (CycloneDX 1.6 JSON).

Pure file checks against this checkout, no network, no DB: the server's
SBOM holds every pin of the Linux locks with its hashes, the web's covers
every vendored browser file at the version the folder says, and the app's
turns sbom-android.init.gradle's output into components and a dependency
graph. Every SBOM is checked for the parts of CycloneDX a reader relies on
(unique bom-refs, every dependency naming a component that is there).
"""

from __future__ import annotations

import importlib.util
import json
import re
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
SCRIPT = REPO / "scripts" / "release" / "sbom.py"


def _load():
    spec = importlib.util.spec_from_file_location("release_sbom", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["release_sbom"] = mod
    spec.loader.exec_module(mod)
    return mod


sbom = _load()
VENDOR = REPO / "web" / "static" / "vendor"


def _refs(doc: dict) -> list[str]:
    out = []

    def walk(comps):
        for c in comps:
            out.append(c["bom-ref"])
            walk(c.get("components") or [])
    walk(doc["components"])
    return out


def _well_formed(doc: dict) -> None:
    """What every reader of the SBOM relies on."""
    assert doc["bomFormat"] == "CycloneDX" and doc["specVersion"] == "1.6" and doc["version"] == 1
    assert re.fullmatch(r"urn:uuid:[0-9a-f-]{36}", doc["serialNumber"])
    assert re.fullmatch(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ", doc["metadata"]["timestamp"])
    root = doc["metadata"]["component"]
    refs = _refs(doc)
    assert len(refs) == len(set(refs)), "bom-refs are unique"
    assert root["bom-ref"] not in refs
    known = set(refs) | {root["bom-ref"]}
    assert doc["dependencies"][0]["ref"] == root["bom-ref"]
    for d in doc["dependencies"]:
        assert d["ref"] in known
        assert set(d["dependsOn"]) <= known, d["ref"]

    def hashes(comps):
        for c in comps:
            for h in c.get("hashes") or []:
                assert h["alg"] == "SHA-256" and re.fullmatch(r"[0-9a-f]{64}", h["content"])
            for lic in c.get("licenses") or []:
                assert set(lic) in ({"license"}, {"expression"})
            hashes(c.get("components") or [])
    hashes(doc["components"])
    json.dumps(doc)


