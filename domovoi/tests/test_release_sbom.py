def test_every_vendored_script_and_stylesheet_is_in_the_web_table_once():
    shipped = {p for p in VENDOR.rglob("*") if p.is_file() and p.suffix in (".js", ".mjs", ".css")}
    owners: dict[Path, list[str]] = {}
    for entry in sbom.WEB_LIBRARIES:
        for p in sbom.web_files(entry, VENDOR):
            owners.setdefault(p, []).append(entry["name"])
    missing = sorted(p.relative_to(VENDOR).as_posix() for p in shipped - set(owners))
    assert not missing, f"vendored files no WEB_LIBRARIES entry covers (add them to scripts/release/sbom.py): {missing}"
    twice = {p.relative_to(VENDOR).as_posix(): n for p, n in owners.items() if len(n) > 1}
    assert not twice


@pytest.mark.parametrize("entry", sbom.WEB_LIBRARIES, ids=lambda e: e["name"])
def test_each_web_library_s_version_is_the_one_its_files_or_docs_say(entry):
    """A bump of the files without the table (or the other way) fails here."""
    folder = VENDOR / entry["files"][0].split("/")[0]
    places = [folder / "README.md", REPO / "docs" / "LICENSES.md", *sbom.web_files(entry, VENDOR)[:1]]
    text = "\n".join(p.read_text(encoding="utf-8", errors="replace") for p in places if p.is_file())
    assert entry["version"] in text, f"{entry['name']} {entry['version']}: not in {[p.name for p in places]}"


def test_the_web_sbom_hashes_each_shipped_file_and_lists_what_bundles_carry():
    doc = sbom.web_bom(REPO, "v9.9.9")
    _well_formed(doc)
    by = {c["name"]: c for c in doc["components"]}
    react = by["react"]
    assert react["purl"] == "pkg:npm/react@18.3.1" and react["licenses"] == [{"license": {"id": "MIT"}}]
    (f,) = react["components"]
    assert f["type"] == "file" and f["name"] == "web/static/vendor/react/react.development.js"
    assert f["hashes"][0]["content"] == sbom.sha256_file(REPO / f["name"])
    assert by["@babel/standalone"]["purl"] == "pkg:npm/%40babel/standalone@7.29.0"
    inner = {c["name"]: c for c in by["domovoi-tiptap-bundle"]["components"] if c["type"] == "library"}
    listed = json.loads((VENDOR / "tiptap" / "THIRD-PARTY.json").read_text(encoding="utf-8"))
    assert set(inner) == {e["name"] for e in listed}
    univer = [c for c in by["domovoi-univer-bundle"]["components"] if c["type"] == "library"]
    assert len(univer) > 20 and any(c["name"] == "@flatten-js/interval-tree" for c in univer)
    assert by["butterchurn"]["pedigree"]["notes"].startswith("Modified:")
    assert {"expression": "Apache-2.0 OR MPL-2.0"} in [
        lic for c in by["@excalidraw/excalidraw"]["components"] for lic in c.get("licenses") or []]


