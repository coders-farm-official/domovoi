GRADLE_DEPS = {
    "format": 1, "configuration": "releaseRuntimeClasspath",
    "roots": ["androidx.core:core:1.15.0", "androidx.compose:compose-bom:2025.01.00"],
    "components": [
        {"group": "androidx.core", "module": "core", "version": "1.15.0",
         "dependencies": ["org.jetbrains.kotlin:kotlin-stdlib:2.4.20"],
         "artifacts": [{"file": "core-1.15.0.aar", "sha256": "4" * 64}]},
        {"group": "org.jetbrains.kotlin", "module": "kotlin-stdlib", "version": "2.4.20", "dependencies": [],
         "artifacts": [{"file": "kotlin-stdlib-2.4.20.jar", "sha256": "5" * 64}]},
        {"group": "androidx.compose", "module": "compose-bom", "version": "2025.01.00", "dependencies": [],
         "artifacts": []},
    ],
}


def test_the_app_sbom_is_gradle_s_release_classpath_and_the_speech_library(tmp_path):
    deps = tmp_path / "deps.json"
    deps.write_text(json.dumps(GRADLE_DEPS), encoding="utf-8")
    doc = sbom.android_bom(REPO, "v9.9.9", deps)
    _well_formed(doc)
    name, code = sbom.app_version(REPO)
    root = doc["metadata"]["component"]
    assert root["name"] == "com.domovoi.app" and root["version"] == name and str(code) in root["description"]
    by = {c["bom-ref"]: c for c in doc["components"]}
    core = by["pkg:maven/androidx.core/core@1.15.0"]
    assert core["group"] == "androidx.core" and core["hashes"] == [{"alg": "SHA-256", "content": "4" * 64}]
    assert "hashes" not in by["pkg:maven/androidx.compose/compose-bom@2025.01.00"]
    graph = {d["ref"]: d["dependsOn"] for d in doc["dependencies"]}
    assert graph["pkg:maven/androidx.core/core@1.15.0"] == ["pkg:maven/org.jetbrains.kotlin/kotlin-stdlib@2.4.20"]
    sherpa = [c for c in doc["components"] if c["name"] == "sherpa-onnx"]
    (sherpa,) = sherpa
    assert sherpa["bom-ref"] in graph["com.domovoi.app"]
    sums = dict(reversed(line.split("  ", 1)) for line in
                (REPO / sbom.SHERPA / "SHA256SUMS").read_text(encoding="utf-8").splitlines() if line.strip())
    assert {f["name"]: f["hashes"][0]["content"] for f in sherpa["components"]} == {
        f"{sbom.SHERPA}/jniLibs/{abi}/libsherpa-onnx-jni.so": sums[f"jniLibs/{abi}/libsherpa-onnx-jni.so"]
        for abi in sbom.RELEASE_ABIS}


def test_app_gradle_output_that_is_not_the_init_script_s_is_refused(tmp_path):
    deps = tmp_path / "deps.json"
    deps.write_text(json.dumps({**GRADLE_DEPS, "configuration": "debugRuntimeClasspath"}), encoding="utf-8")
    with pytest.raises(sbom.Refused, match="releaseRuntimeClasspath"):
        sbom.android_bom(REPO, "v9.9.9", deps)
    broken = json.loads(json.dumps(GRADLE_DEPS))
    broken["components"][0]["dependencies"] = ["a:b:1"]
    deps.write_text(json.dumps(broken), encoding="utf-8")
    with pytest.raises(sbom.Refused, match="depends on a:b:1"):
        sbom.android_bom(REPO, "v9.9.9", deps)


def test_the_release_abis_are_the_ones_release_ps1_publishes():
    text = (REPO / "android" / "scripts" / "release.ps1").read_text(encoding="utf-8")
    m = re.search(r"^\$Abis = @\(([^)]*)\)", text, re.M)
    assert m, "release.ps1 names its ABIs in $Abis"
    assert tuple(re.findall(r"'([^']+)'", m.group(1))) == sbom.RELEASE_ABIS


def test_the_init_script_uses_gradle_s_api_only():
    """No plugin, no repository, no download of its own: what it reads is
    what the release build resolves (and Gradle's verification covers)."""
    text = (REPO / "scripts" / "release" / "sbom-android.init.gradle").read_text(encoding="utf-8")
    code = "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("//"))
    for banned in ("repositories", "classpath(", "classpath \"", "apply plugin", "plugins {", "http://", "https://", "initscript"):
        assert banned not in code, banned
    assert "releaseRuntimeClasspath" in code and "domovoiSbomDeps" in code


