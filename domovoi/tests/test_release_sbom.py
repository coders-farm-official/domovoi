def test_the_command_writes_each_kind(tmp_path, capsys):
    for kind in ("server", "web"):
        out = tmp_path / sbom.ASSET_NAMES[kind]
        assert sbom.main([kind, "--tag", "v9.9.9", "--out", str(out)]) == 0
        doc = json.loads(out.read_text(encoding="utf-8"))
        assert doc["metadata"]["component"]["version"] == "9.9.9"
    assert sbom.main(["android", "--out", str(tmp_path / "a.json")]) == 1
    assert "needs --gradle-deps" in capsys.readouterr().err
