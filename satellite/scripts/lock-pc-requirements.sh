#!/usr/bin/env bash
# Regenerate satellite/locks/pc-<python>-<machine>.txt: the hash-pinned
# package lists satellite/scripts/install-pc.sh installs on a spare computer
# (pip --require-hashes --only-binary=:all: --no-deps), one per Python
# version and machine the installer supports.
#
# The installer checks every download against these SHA-256 hashes, and
# the lists reach the computer inside the core's bundle, whose own SHA-256
# the dashboard's command checks first. So PyPI supplies the bytes but
# does not choose them: a changed or substituted file is refused.
#
# Needs uv (https://docs.astral.sh/uv/, MIT/Apache-2.0) and the internet.
# Run from anywhere: bash satellite/scripts/lock-pc-requirements.sh
# A target whose requirements have no wheel (onnxruntime's ARM pin on a new
# Python, say) gets no list, and the installer says that Python and
# machine are not supported yet.

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/../.."
command -v uv >/dev/null 2>&1 || { echo "needs uv (pip install uv)" >&2; exit 1; }

OUT=satellite/locks
# The oldest glibc the installer supports: 2.28, since a computer whose own
# Python is too old (Ubuntu 22.04: glibc 2.35, Debian 11: 2.31) installs
# these lists with the satellite's own Python (satellite/locks/
# linux-python.txt), and numpy, scipy and onnxruntime publish
# manylinux_2_28 wheels. A version the list names then has a wheel for
# every supported release (on 2026-10-15, resolving at 2_28 and at 2_36
# picked the same versions).
GLIBC=2_28
PYTHONS="3.11 3.12 3.13 3.14"
MACHINES="x86_64 aarch64"

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
# spidev drives a Pi HAT's LEDs: never on a spare computer.
grep -viE '^[[:space:]]*spidev([^A-Za-z0-9_-]|$)' satellite/requirements.txt >"$WORK/in.txt"
grep -vE '^[[:space:]]*(#|$)' satellite/requirements-pc.txt >>"$WORK/in.txt"
echo "openwakeword==0.6.0" >"$WORK/oww.txt"

mkdir -p "$OUT"
for machine in $MACHINES; do
  for py in $PYTHONS; do
    tag=cp${py/./}
    dest=$OUT/pc-$tag-$machine.txt
    common=(--quiet --python-version "$py" --python-platform "$machine-manylinux_$GLIBC"
            --generate-hashes --no-build --no-header)
    if ! uv pip compile "$WORK/in.txt" "${common[@]}" --output-file "$WORK/main.txt" 2>"$WORK/err.txt"; then
      echo "no list for Python $py on $machine: $(tail -n 3 "$WORK/err.txt")"
      rm -f "$dest"
      continue
    fi
    uv pip compile "$WORK/oww.txt" "${common[@]}" --no-deps --output-file "$WORK/oww-lock.txt"
    {
      echo "# Hash-pinned packages for a spare-computer satellite: CPython $py on $machine"
      echo "# (manylinux_$GLIBC wheels). Generated by satellite/scripts/lock-pc-requirements.sh"
      echo "# from satellite/requirements.txt (without spidev) and requirements-pc.txt;"
      echo "# install-pc.sh installs it with pip --require-hashes --only-binary=:all: --no-deps."
      echo "# Do not edit by hand: change the requirements and run the script."
      echo
      grep -vE '^#' "$WORK/main.txt"
      echo
      echo "# openwakeword itself, without its dependencies (requirements.txt says why)"
      grep -vE '^#' "$WORK/oww-lock.txt"
    } >"$dest"
    echo "wrote $dest"
  done
done
