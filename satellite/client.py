    def _apply_config_changes(self, changes: dict[str, Any]) -> None:
        """Merge web-edited config into ~/.domovoi/config.toml (preserving
        comments), then restart to apply. Validates the merged file parses
        BEFORE writing and keeps a .bak, so a bad edit can't brick the Pi —
        if it won't parse we abort with nothing written; if it parses but is
        semantically wrong, the .bak is the SSH-side manual escape."""
        try:
            original = CONFIG_PATH.read_text(encoding="utf-8")
        except OSError as e:
            log.warning("set_config: can't read %s: %s", CONFIG_PATH, e)
            return
        merged = config_writer.apply_changes(original, changes)
        try:
            tomllib.loads(merged)
        except Exception as e:
            log.error(
                "set_config: merged config doesn't parse (%s); aborting, "
                "nothing written", e,
            )
            return
        backup = CONFIG_PATH.with_name(CONFIG_PATH.name + ".bak")
        try:
            backup.write_text(original, encoding="utf-8")
            CONFIG_PATH.write_text(merged, encoding="utf-8")
        except OSError as e:
            log.error("set_config: failed to write %s: %s", CONFIG_PATH, e)
            return
        log.info(
            "set_config: applied %d change(s) to %s (backup at %s); restarting",
            len(changes), CONFIG_PATH, backup,
        )
        self._restart_service()

    def _read_output_volume(self) -> int | None:
        """Current hardware output volume %, or None if no control is
        configured for this board or amixer can't read it."""
        ctrl = self.cfg.output_mixer_control
        if not ctrl:
            return None
        try:
            r = subprocess.run(
                _volume.get_command(self.cfg.output_mixer_card, ctrl),
                capture_output=True, text=True, timeout=5.0,
            )
        except (FileNotFoundError, subprocess.TimeoutExpired) as e:
            log.warning("amixer get for volume failed: %s", e)
            return None
        if r.returncode != 0:
            log.warning(
                "amixer get %r on card %s failed: %s",
                ctrl, self.cfg.output_mixer_card, r.stderr.strip()[:120],
            )
            return None
        return _volume.parse_volume_percent(r.stdout)

    def _apply_output_volume(self, level: int) -> None:
        """Set the hardware output volume, then re-read and report it so the
        server's cache reflects the real level. Best-effort — a board
        with no configured control, or an amixer failure, is logged and
        skipped, never raised (a failed volume change must not take down the
        receiver path)."""
        ctrl = self.cfg.output_mixer_control
        if not ctrl:
            log.info(
                "set_volume ignored: no [audio] output_mixer_control configured "
                "for device profile %r. Set it to this board's ALSA playback "
                "control to enable voice/music volume control.",
                self.cfg.device.name,
            )
            return
        level = _volume.clamp(level)
        try:
            r = subprocess.run(
                _volume.set_command(self.cfg.output_mixer_card, ctrl, level),
                capture_output=True, text=True, timeout=5.0,
            )
        except (FileNotFoundError, subprocess.TimeoutExpired) as e:
            log.warning("amixer set for volume failed: %s", e)
            return
        if r.returncode != 0:
            log.warning(
                "amixer set %r=%d%% on card %s failed: %s",
                ctrl, level, self.cfg.output_mixer_card, r.stderr.strip()[:120],
            )
            return
        log.info(
            "output volume set to %d%% (%s on card %s)",
            level, ctrl, self.cfg.output_mixer_card,
        )
        actual = self._read_output_volume()
        self._emit_volume_status(actual if actual is not None else level)

    def _wifi_watcher_thread_run(self) -> None:
        """Periodic rx-bitrate poll + reassociate-on-trouble.

        Loop:
          1. Wait one poll interval (interruptible by shutdown).
          2. Sample link via `_check_wifi_link`.
          3. Push the sample to the server (no-op if WS down).
          4. If WS has been disconnected past the degraded threshold,
             arm the local degraded flag so the next wake word plays
             the canned MP3 instead of trying to stream.
          5. If rx bitrate is below `min_healthy_mbits`:
             a. Honor cooldown — recently-reassociated, just arm the
                degraded flag and move on.
             b. Otherwise reassociate, settle for ~3 s, re-sample.
                Healthy after → clear degraded; still bad → arm degraded.
          6. If rx bitrate is healthy and WS is connected, clear degraded.

        Disabled at runtime when `cfg.wifi_enabled = false` or when
        `iw` isn't installed (single warning logged, then thread exits).
        """
        if not self.cfg.wifi_enabled:
            log.info("wifi watcher disabled by config")
            return
        last_reassociate = 0.0  # monotonic; 0 means "never"
        while not self.shutdown_event.is_set():
            # Interruptible sleep — shutdown_event.wait returns True
            # when the event flips, False on timeout.
            if self.shutdown_event.wait(self.cfg.wifi_poll_interval_sec):
                return
            if not self.cfg.wifi_enabled:
                return  # disabled mid-flight (e.g., iw missing)

            # WS-disconnect-too-long degraded check. The wifi watcher
            # is the natural place: it's already polling at the right
            # cadence and consolidates the "should we be in degraded
            # mode" decision in one spot.
            ws_down_for: float | None = None
            if self._ws_disconnected_since is not None:
                ws_down_for = time.monotonic() - self._ws_disconnected_since
                if ws_down_for > self.cfg.wifi_degraded_after_disconnect_sec:
                    if not self._network_degraded.is_set():
                        log.warning(
                            "WS disconnected for %.0fs; arming network_degraded "
                            "so the next wake word gets the canned message",
                            ws_down_for,
                        )
                    self._network_degraded.set()

            link = self._check_wifi_link()
            if link is None:
                continue
            self._emit_wifi_status(link)

            rx = link.get("rx_mbits")
            if rx is None:
                # Link is down or output didn't include the rate line
                # (rare). Don't try to reassociate when there's no
                # connection at all — wpa_supplicant will be cycling
                # through its own reconnect logic and we'd just fight it.
                continue

            if rx >= self.cfg.wifi_min_healthy_mbits:
                # Healthy. Clear degraded *only* when WS is also up —
                # otherwise the rate is fine but we still can't reach
                # the server and the canned MP3 is still the
                # right behavior on next wake.
                if self._ws_disconnected_since is None and self._network_degraded.is_set():
                    log.info("wifi healthy (rx=%.1f Mbit/s); clearing degraded flag", rx)
                    self._network_degraded.clear()
                continue

            now = time.monotonic()
            cooldown_remaining = self.cfg.wifi_cooldown_sec - (now - last_reassociate)
            if last_reassociate > 0 and cooldown_remaining > 0:
                # Only arm degraded if WS is also down. A slow rate the
                # user can still talk through (TTS may chop, but the bot
                # still answers) doesn't merit the canned "I can't reach
                # the network" message — that message is for genuine
                # server unreachability, not "things are slow."
                # Fixed 2026-05-07 after a user report of stuck-canned
                # state surviving WS reconnect.
                if self._ws_disconnected_since is not None:
                    log.warning(
                        "wifi rx=%.1f Mbit/s below %.1f and WS down for "
                        "%.0fs; arming degraded mode (cooldown blocks "
                        "reassociate for %.0fs more)",
                        rx, self.cfg.wifi_min_healthy_mbits,
                        now - self._ws_disconnected_since, cooldown_remaining,
                    )
                    self._network_degraded.set()
                else:
                    log.warning(
                        "wifi rx=%.1f Mbit/s below %.1f, but WS is up — "
                        "user can still talk to Domovoi; not "
                        "arming degraded. Cooldown blocks reassociate "
                        "for %.0fs more.",
                        rx, self.cfg.wifi_min_healthy_mbits, cooldown_remaining,
                    )
                continue

            log.warning(
                "wifi rx=%.1f Mbit/s (ssid=%r) below threshold %.1f; reassociating",
                rx, link.get("ssid"), self.cfg.wifi_min_healthy_mbits,
            )
            ok = self._reassociate_wifi()
            last_reassociate = time.monotonic()
            if not ok:
                self._network_degraded.set()
                continue

            # Settle for the AP/STA to renegotiate before re-sampling.
            # 3 s is empirically enough on the incident hardware (rate
            # jumped from 1 → 28+ Mbit/s within a second of reassociate).
            if self.shutdown_event.wait(3.0):
                return
            link2 = self._check_wifi_link()
            if link2 is None:
                continue
            self._emit_wifi_status(link2)
            rx2 = link2.get("rx_mbits")
            if rx2 is not None and rx2 >= self.cfg.wifi_min_healthy_mbits:
                log.info(
                    "wifi reassociate recovered: rx=%.1f Mbit/s (was %.1f)",
                    rx2, rx,
                )
                if self._ws_disconnected_since is None:
                    self._network_degraded.clear()
            else:
                # Same WS-up guard as the cooldown branch — if the user
                # can still talk to Domovoi (WS up), the
                # canned message would deny them help even though the
                # bot is reachable. Only arm degraded when WS is also
                # genuinely down.
                if self._ws_disconnected_since is not None:
                    log.warning(
                        "wifi reassociate did not recover rate (now "
                        "rx=%s) and WS is down; arming degraded mode "
                        "until next try after cooldown",
                        rx2,
                    )
                    self._network_degraded.set()
                else:
                    log.warning(
                        "wifi reassociate did not recover rate (now "
                        "rx=%s) but WS is up — leaving degraded clear "
                        "so user can still reach Domovoi",
                        rx2,
                    )

    def _play_canned_mp3(self, mp3_path: Path, label: str) -> None:
        """Blocking play of a pre-rendered MP3 via mpg123 → ALSA.

        Used for the network-issues canned message — fires when the
        Pi has been disconnected long enough OR the watcher gave up
        on a reassociate. Keeps the user in the loop with a real
        explanation instead of silent failure.

        Held synchronously because the caller (`_wait_for_wake`) needs
        to know when the message has finished playing before going
        back to listen — otherwise wake-word predict could fire on
        the canned MP3's own audio bleeding into the mic.
        """
        if not mp3_path.exists():
            log.warning(
                "canned %s MP3 missing at %s — skipping playback. "
                "Has the Domovoi server regenerated canned sounds and "
                "synced satellite/sounds to this Pi?",
                label, mp3_path,
            )
            return
        self._leds.set_state("error")
        try:
            result = subprocess.run(
                [
                    "mpg123", "-q",
                    *_volume.mpg123_scale_args(self.cfg.tts_playback_gain),
                    "-o", "alsa",
                    "-a", self.cfg.music_alsa_device,
                    str(mp3_path),
                ],
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.PIPE,
                timeout=15.0,
            )
            if result.returncode != 0:
                log.warning(
                    "mpg123 canned playback rc=%d stderr=%s",
                    result.returncode,
                    (result.stderr or b"").decode(errors="replace")[:200],
                )
        except FileNotFoundError:
            log.warning("mpg123 not installed on this Pi; canned %s skipped", label)
        except subprocess.TimeoutExpired:
            log.warning("mpg123 canned playback timed out (15s)")
        finally:
            # Drop back to the appropriate idle state — _wait_for_wake
            # caller will set "listening" again on the next attempt.
            self._leds.set_state_unless("listening", "idle")

    def _deferred_pi_action(self, action: str, arg: str | None = None) -> None:
        """Wait for TTS playback to drain, then run the requested
        Pi-local action. Called from the receiver loop's response_end
        handler in a daemon thread so the asyncio loop isn't blocked.
        """
        if not self._playback_idle.wait(timeout=10.0):
            log.warning(
                "pi_action=%s: playback didn't drain within 10s; "
                "running action anyway",
                action,
            )
        if action == "reassociate_wifi":
            log.info("pi_action: voice-triggered wifi reassociate")
            self._reassociate_wifi()
        elif action == "set_voice":
            self._apply_voice_switch(arg)
        elif action == "restart":
            log.info("pi_action: restarting satellite service to apply config")
            self._restart_service()
        else:
            log.warning("pi_action: ignoring unknown action %r", action)

    def _apply_upgrade(self, payload: dict[str, Any]) -> None:
        """Self-upgrade this satellite (Feature 10): mirror the server's
        `satellite/` tree, then restart into the new code. Runs on a daemon
        worker thread (blocking HTTP + tarball backup + service restart).

        Order is failure-safe:
          1. Capture the PRE-upgrade version label + manifest (the watchdog
             needs them to revert exactly), then tarball the whole tree.
          2. Sync the code — on ANY error (network, sha256 mismatch, disk),
             restore the partial writes from the backup and DO NOT restart:
             the old code stays running and the on-disk tree stays consistent.
          3. On success: persist the new version label + manifest.
          4. Drop the pending marker (timeout DURATION + backup + the exact
             revert data) so the post-restart watchdog can roll back if the
             new code never reaches a `ready` frame, then restart the service.
          5. If the restart command itself fails, roll everything back now so
             stale new code can never boot later with no watchdog armed.

        The http_base is derived from our own live WS URL exactly as
        `_sync_sounds` does — the upgrade frame carries PATHS, never absolute
        URLs. Every filesystem op is OSError-guarded so a sidecar write hiccup
        can't crash the worker mid-upgrade."""
        http_base = sound_sync.http_base_from_ws(self.cfg.domovoi_url)
        expected_sha = payload.get("expected_sha")
        timeout = float(payload.get("reconnect_timeout_sec", 90))

        # (1) Snapshot the pre-upgrade label + manifest BEFORE anything is
        # overwritten — the rollback path replays these to revert exactly.
        prev_sha = _read_synced_sha()
        prev_manifest_text = ""
        prev_manifest: dict[str, str] = {}
        try:
            if SYNCED_MANIFEST_SIDECAR.is_file():
                prev_manifest_text = SYNCED_MANIFEST_SIDECAR.read_text(encoding="utf-8")
                prev_manifest = json.loads(prev_manifest_text)
        except (OSError, ValueError) as e:
            log.warning("upgrade: previous manifest unreadable (%s); pruning nothing", e)

        # Atomic backup before any write.
        try:
            code_sync.backup_tree(SATELLITE_ROOT, UPGRADE_BACKUP)
        except Exception as e:
            log.error("upgrade: backup failed, aborting (no changes made): %s", e)
            return

        # (2) Sync — on ANY failure restore the partial writes from the backup
        # (a mid-batch sha mismatch may already have overwritten earlier files)
        # and DO NOT restart: the old code in memory + the on-disk tree both
        # stay consistent.
        try:
            result = code_sync.sync_code(http_base, SATELLITE_ROOT, CODE_EXT_ALLOW, prev_manifest)
        except Exception as e:
            log.error("upgrade: code sync failed; restoring tree, not restarting: %s", e)
            try:
                code_sync.restore_tree(UPGRADE_BACKUP, SATELLITE_ROOT)
            except Exception as re:
                log.error("upgrade: post-failure restore FAILED (%s); manual SSH restore may be needed", re)
            return
        log.info(
            "upgrade: synced sha=%s (%d downloaded, %d pruned)",
            expected_sha, result["downloaded"], len(result["pruned"]),
        )

        # (2b) IMPORT SELF-CHECK before restarting. The synced tree can still be
        # un-runnable even on a clean 0-downloaded sync — e.g. the on-disk
        # client.py references a sibling module the manifest never carried (an
        # inconsistent earlier hand-deploy, a transient). Restarting into that
        # crash-loops the service, and because it dies ON IMPORT the reconnect
        # watchdog never even arms to roll back. So dry-run the import in a fresh
        # subprocess (no audio device is grabbed at import time); on ANY failure,
        # restore the backup and DON'T restart — the old in-memory process keeps
        # serving and the room stays online instead of bricking on a bounce.
        try:
            check = subprocess.run(
                [sys.executable, "-c", "import satellite.client"],
                cwd=str(SATELLITE_ROOT.parent),
                capture_output=True,
                text=True,
                timeout=120,
            )
        except Exception as e:  # noqa: BLE001 — timeout / OSError → treat as failure
            log.error("upgrade: import self-check could not run (%s); aborting to be safe", e)
            check = None
        if check is None or check.returncode != 0:
            tail = (check.stderr or "")[-600:] if check is not None else "self-check did not run"
            log.error(
                "upgrade: synced code fails to import; restoring + NOT restarting: %s", tail
            )
            try:
                code_sync.restore_tree(UPGRADE_BACKUP, SATELLITE_ROOT)
            except Exception as re:  # noqa: BLE001
                log.error("upgrade: post-failure restore FAILED (%s); manual SSH restore may be needed", re)
            return

        # Files this upgrade ADDED (present in the new manifest, absent from the
        # old) — the watchdog unlinks these before restoring so a rollback is
        # byte-exact (tarfile.extractall alone never deletes added files).
        added_files = sorted(set(result["manifest"]) - set(prev_manifest))

        # (3) Persist the new version label + manifest for the next prune base.
        try:
            SYNCED_SHA_SIDECAR.write_text((expected_sha or "") + "\n", encoding="utf-8")
        except OSError as e:
            log.warning("upgrade: failed to write synced_sha sidecar: %s", e)
        try:
            SYNCED_MANIFEST_SIDECAR.write_text(json.dumps(result["manifest"]), encoding="utf-8")
        except OSError as e:
            log.warning("upgrade: failed to write synced_manifest sidecar: %s", e)

        # (4) Arm the rollback watchdog (via marker) then restart into new code.
        # The marker stores the timeout DURATION (not an absolute deadline) so
        # the watchdog measures from new-process boot — a slow reboot doesn't
        # eat into the window. It also carries the exact revert data.
        try:
            UPGRADE_PENDING_MARKER.write_text(json.dumps({
                "timeout": timeout,
                "backup": str(UPGRADE_BACKUP),
                "prev_sha": prev_sha,
                "prev_manifest": prev_manifest_text,
                "added_files": added_files,
            }), encoding="utf-8")
        except OSError as e:
            log.warning("upgrade: failed to write pending marker (no auto-rollback): %s", e)

        # (5) Restart into the new code. We deliberately DO NOT roll back on a
        # falsey return: `systemctl --no-block restart` is fire-and-forget, and
        # systemd SIGTERMs THIS process (and the `systemctl` child it just
        # spawned) as it tears the unit down — so the call routinely reports
        # non-zero even though the restart absolutely happens. Treating that as
        # "restart failed → roll back" deleted the freshly-written version
        # sidecar and reverted perfectly good code on a healthy bounce.
        #
        # The real safety nets live elsewhere and cover both outcomes:
        #   • restart fired (the normal case) → new code boots → the reconnect
        #     watchdog, armed from the marker above, rolls back iff it never
        #     reconnects/handshakes within the window;
        #   • restart genuinely never fired (e.g. missing sudoers) → the old
        #     in-memory process keeps serving (room stays online), the new code
        #     + sidecar sit staged on disk, and the next restart boots them and
        #     arms the watchdog. Nothing is lost; nothing crash-loops.
        # So here we only fire-and-log.
        if not self._restart_service():
            log.warning(
                "upgrade: restart command returned non-zero — it was almost "
                "certainly still queued via --no-block (systemd SIGTERMs this "
                "process mid-call). New code + version sidecar are staged and "
                "the watchdog will arm on the next boot; not rolling back."
            )

    def _rollback_upgrade(
        self,
        backup: Path,
        prev_sha: str | None,
        prev_manifest_text: str,
        added_files: list[str],
    ) -> None:
        """Revert an upgrade EXACTLY: unlink files the upgrade added, restore
        the pre-upgrade tarball over the tree, and revert the version-label +
        manifest sidecars so the dashboard stops reporting the new SHA the
        satellite no longer runs (and the next prune baseline is the real prior
        manifest, not the failed one). Best-effort; every step is guarded."""
        for rel in added_files or []:
            if not code_sync._safe_rel(rel) or Path(rel).suffix not in CODE_EXT_ALLOW:
                continue
            try:
                (SATELLITE_ROOT / rel).unlink(missing_ok=True)
            except OSError:
                pass
        try:
            code_sync.restore_tree(backup, SATELLITE_ROOT)
        except Exception as e:
            log.error("upgrade rollback: tarball restore FAILED (%s); manual SSH restore from %s needed", e, backup)
        try:
            if prev_sha:
                SYNCED_SHA_SIDECAR.write_text(prev_sha + "\n", encoding="utf-8")
            else:
                SYNCED_SHA_SIDECAR.unlink(missing_ok=True)
        except OSError:
            pass
        try:
            if prev_manifest_text:
                SYNCED_MANIFEST_SIDECAR.write_text(prev_manifest_text, encoding="utf-8")
            else:
                SYNCED_MANIFEST_SIDECAR.unlink(missing_ok=True)
        except OSError:
            pass

    def _arm_upgrade_watchdog(self) -> None:
        """On startup, check for a pending self-upgrade (Feature 10) and arm a
        best-effort rollback. The marker carries the timeout DURATION, so the
        deadline is measured from THIS boot (a slow reboot can't eat the
        window). Spawn a daemon thread that waits out the deadline and — unless
        a `ready` frame has by then set `_upgrade_confirmed` — rolls the tree +
        version back and restarts onto the old code.

        No restart loop: the watchdog clears the marker as part of rolling
        back, so the rolled-back old code boots with no marker. A healthy boot
        that finds a stale marker also clears it on the `ready` frame.

        Caveat (documented v1 limitation): a crash ON IMPORT of the new code
        means this process never reaches here, so it cannot self-rollback —
        systemd just loops. That case needs a manual SSH restore from
        `satellite_backup.tar`. This watchdog only covers code that imports +
        starts but never reaches a clean server handshake.

        UNTESTED — Pi-only path."""
        try:
            if not UPGRADE_PENDING_MARKER.is_file():
                return
            marker = json.loads(UPGRADE_PENDING_MARKER.read_text(encoding="utf-8"))
        except (OSError, ValueError) as e:
            log.warning("upgrade watchdog: unreadable marker (%s); ignoring", e)
            return

        # Deadline measured from THIS boot — the marker stores a duration, not
        # an absolute time, so the reboot itself can't consume the window.
        timeout = float(marker.get("timeout", 90.0))
        deadline = time.time() + timeout
        log.info("upgrade watchdog: armed, rolling back in %.0fs unless confirmed", timeout)
        threading.Thread(
            target=self._upgrade_watchdog_run,
            args=(deadline, marker),
            daemon=True,
            name="upgrade-watchdog",
        ).start()

    def _upgrade_watchdog_run(self, deadline: float, marker: dict[str, Any]) -> None:
        """Wait out the upgrade deadline; if the new code never confirmed
        (no `ready` frame), roll back exactly to the pre-upgrade tree + version
        and restart onto the old code. Interruptible by shutdown."""
        remaining = max(0.0, deadline - time.time())
        # shutdown_event.wait returns True if shutdown fired first → bail.
        if self.shutdown_event.wait(remaining):
            return
        if self._upgrade_confirmed:
            return
        log.error("upgrade watchdog: new code never handshook within the deadline; rolling back")
        self._rollback_upgrade(
            Path(marker.get("backup", str(UPGRADE_BACKUP))),
            marker.get("prev_sha"),
            marker.get("prev_manifest", ""),
            marker.get("added_files", []),
        )
        try:
            UPGRADE_PENDING_MARKER.unlink(missing_ok=True)
        except OSError:
            pass
        self._restart_service()

    def _apply_voice_switch(self, name: str | None) -> None:
        """Persist a voice switch ("switch to <name>") so it survives
        restarts, then re-report it and re-sync this voice's clips. The
        switch confirmation the user just heard was already synthesized in
        the new voice by the server (voice_override); from here on the
        room's normal responses + greetings use it too."""
        if not name:
            log.warning("pi_action set_voice: no voice name provided; ignoring")
            return
        try:
            VOICE_SIDECAR.parent.mkdir(parents=True, exist_ok=True)
            VOICE_SIDECAR.write_text(name.strip() + "\n", encoding="utf-8")
            log.info("pi_action set_voice: now speaking as %r", name)
        except OSError as e:
            log.warning("pi_action set_voice: could not persist %r: %s", name, e)
            return
        # Re-report the new voice so the server's room cache flips for
        # subsequent turns, and pull the new voice's clips into the cache.
        self._emit_voice_status()
        if self.loop is not None:
            asyncio.run_coroutine_threadsafe(self._sync_sounds(), self.loop)

