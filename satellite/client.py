#   SYNCED_MANIFEST_SIDECAR — the last applied manifest, so the NEXT sync can
#                             prune-within-previous (never blind-globs the tree).
#   UPGRADE_PENDING_MARKER  — written just before the restart; the post-restart
#                             watchdog reads it and rolls back from the tarball
#                             if the new code never reaches a `ready` frame.
#   UPGRADE_BACKUP          — atomic tarball of the whole tree taken before any
#                             write, for that rollback.
#   CODE_EXT_ALLOW          — extensions the code channel carries (mirrors the
#                             server-side allowlist; bundled sounds/*.mp3 ride
#                             the separate /v1/sounds channel, not this one).
SATELLITE_ROOT = Path(__file__).resolve().parent
SYNCED_SHA_SIDECAR = CONFIG_DIR / "synced_sha"
SYNCED_MANIFEST_SIDECAR = CONFIG_DIR / "synced_manifest.json"
