# ─── Audio helpers ────────────────────────────────────────────────────────

def _frame_dbfs(frame_bytes: bytes) -> float:
    """Peak-normalized dBFS of an int16 PCM frame. -inf for pure silence."""
    arr = np.frombuffer(frame_bytes, dtype=np.int16)
    if arr.size == 0:
        return float("-inf")
    rms = float(np.sqrt(np.mean(arr.astype(np.float32) ** 2)))
    if rms < 1.0:
        return float("-inf")
    return 20.0 * np.log10(rms / 32767.0)


def _percentile_dbfs(samples: list[float], pct: float) -> float | None:
    """Return the ``pct``th percentile of a list of dBFS values, ignoring
    -inf (pure silence). None when the input is too small to be meaningful.
    """
    finite = [s for s in samples if s != float("-inf")]
    if len(finite) < 50:  # ~1.5 s of frames at 30 ms each — too few to trust
        return None
    finite.sort()
    idx = int(pct * (len(finite) - 1))
    return finite[idx]


def _capture_stats_str(
    sent: int,
    gate_pass: int,
    voiced: int,
    capture_dbfs: list[float],
    gate_dbfs: float,
) -> str:
    """One-line debug summary of a capture window. Surfaces the four
    quantities you actually need to debug "why didn't endpointing
    work":

      * ``frames``            — how many were captured total.
      * ``gate_pass``         — how many were loud enough to clear the
                                noise gate. 0/N means the gate is too
                                tight (or the mic too quiet); N/N means
                                ambient is louder than the gate (gate
                                too loose, or room genuinely noisy).
      * ``voiced``            — how many of those gate-passing frames
                                webrtcvad classified as speech. Big gap
                                between gate_pass and voiced means VAD
                                is rejecting frames the gate let through
                                — usually background noise that's loud
                                but not speech-shaped.
      * ``dBFS median/p95/max``— the loudness distribution of the
                                window, so you can compare against the
                                gate threshold and spot whether the
                                room shifted mid-utterance.
    """
    finite = [d for d in capture_dbfs if d != float("-inf")]
    if finite:
        finite.sort()
        median = finite[len(finite) // 2]
        p95 = finite[int(0.95 * (len(finite) - 1))]
        max_d = finite[-1]
        dist = f"dBFS median={median:.1f} p95={p95:.1f} max={max_d:.1f}"
    else:
        dist = "dBFS median=-inf (all silent)"
    duration_sec = sent * FRAME_MS / 1000.0
    return (
        f"frames={sent} ({duration_sec:.1f}s), gate_pass={gate_pass}/{sent}, "
        f"voiced={voiced}/{sent}, gate={gate_dbfs:.1f}, {dist}"
    )


# ─── Satellite ────────────────────────────────────────────────────────────

class Satellite:
    """Owns the audio I/O threads + the WebSocket connection.

    Threads:
      - sounddevice InputStream callback     →  raw_q (raw 30 ms PCM frames)
      - mic_thread (audio state machine)     →  send_q (text/bytes for server)
      - playback_thread                      →  consumes playback_q, writes OutputStream
      - asyncio main task                    →  WebSocket I/O (sender + receiver)

    Cross-thread signalling:
      - shutdown_event       — global stop
      - response_done        — set on `response_end`, cleared at top of each turn
      - playback_active      — true between `response_start` and `response_end`
      - stop_playback        — set on barge-in to drain the playback queue
    """

    # Absurdity guard for the loaded `noise_gate.dbfs`. Anything tighter
    # than this means VAD never sees a "loud" frame, `speaking` stays
    # False, and capture runs to max_record_seconds before exiting —
    # the symptom is "every command takes the full max-record window
    # to respond, no matter how short the utterance was." Numerically
    # the same value as the auto-tune safety cap; intentional, since
    # both guards exist to protect the same failure mode.
    _NOISE_GATE_ABSURDITY_LIMIT_DBFS = -28.0
    _NOISE_GATE_FALLBACK_DBFS = -45.0

    def __init__(self, cfg: Config) -> None:
        self.cfg = cfg

        # Sanity-check the loaded threshold. If the user has 0.0 (or
        # anything tighter than ~-28 dBFS) in their config, no realistic
        # speech will pass the gate. Log loudly and fall back to a
        # known-sane default; auto-tune will pull it tighter from
        # ambient measurements over the next few minutes.
        if cfg.noise_gate_dbfs > self._NOISE_GATE_ABSURDITY_LIMIT_DBFS:
            log.warning(
                "noise_gate.dbfs = %.1f in config is tighter than the safety "
                "limit (%.1f dBFS) — no realistic speech would pass the gate. "
                "Falling back to %.1f dBFS until auto-tune produces a valid "
                "threshold from real ambient measurements. Edit "
                "~/.domovoi/config.toml [noise_gate] dbfs to a value below "
                "%.1f to silence this warning.",
                cfg.noise_gate_dbfs,
                self._NOISE_GATE_ABSURDITY_LIMIT_DBFS,
                self._NOISE_GATE_FALLBACK_DBFS,
                self._NOISE_GATE_ABSURDITY_LIMIT_DBFS,
            )
            cfg.noise_gate_dbfs = self._NOISE_GATE_FALLBACK_DBFS

        # Cap raw_q to ~2 s of mic frames. The sounddevice callback
        # produces one frame every 30 ms forever; the wake-word loop
        # consumes them one at a time and runs `oww.predict()` (CPU-
        # heavy on Pi Zero 2 W). Any sustained predict-over-realtime
        # spike — GC pause, thermal throttle, swap — would otherwise
        # let the queue grow unbounded, making wake detection process
        # audio from minutes ago. The "shout the wake word and it
        # finally fires several minutes later" symptom is exactly
        # this. With a bounded queue and drop-oldest semantics in the
        # callback, lag is capped at the queue size, so the detector
        # always sees recent audio.
        self.raw_q: queue.Queue[bytes] = queue.Queue(
            maxsize=int(2.0 * 1000 / FRAME_MS)
        )
        # Counter + last-log timestamp for rate-limited "we dropped
        # frames" warnings. Without this, a single stuck moment would
        # spam the journal at 33 Hz.
        self._raw_q_drops = 0
        self._raw_q_last_drop_log = 0.0
        self.playback_q: queue.Queue[tuple[int, bytes]] = queue.Queue()
        self.send_q: asyncio.Queue[tuple[str, Any]] | None = None  # set in run()

        self.shutdown_event = threading.Event()
        self.response_done = threading.Event()
        self.playback_active = threading.Event()
        self.stop_playback = threading.Event()
        # Set by the receiver when a `response_end` frame carries
        # `expect_followup=true`. The mic-thread inner loop checks this
        # and, if set, captures the next utterance without going back
        # to the wake-word listen — so a "did I get that right?"
        # question doesn't force the user to say "Hey Jarvis" again.
        self.expect_followup = threading.Event()
        # Two-way drop-in (Feature 4) — open-mic mode. Set by the receiver
        # on a `dropin_start` frame; the mic thread observes it and switches
        # from the wake→capture→response cycle to a continuous open-mic relay
        # loop (`_dropin_loop`), streaming every frame to the peer while still
        # running openWakeWord so "hey jarvis, hang up" ends the call.
        # `_dropin_rate` is the inbound relay PCM rate (16 kHz) the playback
        # thread must use so peer audio isn't chipmunked (it is NOT the last
        # response_start TTS rate). UNTESTED on the dev host — Pi-only.
        self.dropin_active = threading.Event()
        self._dropin_rate = 16_000
        # Wake-word training (Feature #5) — clip-recording mode. Like
        # `dropin_active`, this is a mic-thread STATE (set by the receiver
        # thread on a `start_wake_recording` frame, observed by the mic
        # thread), NOT a second raw_q consumer: a single mic thread owns the
        # queue, so two consumers would each steal half the frames. While set
        # it SUSPENDS the normal wake loop and runs `_wake_recording_loop`,
        # which captures N short positive clips and streams them to the
        # server (each as utterance_start(trigger='wake_clip') → PCM →
        # utterance_end). The server writes a WAV per clip instead of routing.
        # `_wake_rec_params` carries {slug, clip_seconds, target_count} from
        # the start frame. UNTESTED on the dev host — Pi-only (no PortAudio).
        self.wake_recording = threading.Event()
        self._wake_rec_params: dict[str, Any] | None = None
        # Conversational chat mode (Feature #8) — Letta-backed open mic. Like
        # `dropin_active` and `wake_recording`, this is a mic-thread STATE: the
        # receiver thread sets it on a `chat_start` frame and clears it on
        # `chat_end`, the mic thread observes it in its outer loop. While set it
        # SUSPENDS the wake loop and runs `_chat_loop`, which runs one normal
        # STT→Letta→TTS turn at a time WITHOUT the wake-word gate (the user can
        # just keep talking). It is NOT a peer relay like drop-in — chat audio
        # follows the ordinary capture+respond path, only minus the wake word.
        # The server clears chat mode and sends `chat_end` on an exit phrase
        # ("that's all", "stop", "never mind"), which breaks this loop. Gated
        # server-side on settings.chat_mode_enabled AND on this board having AEC
        # (supports_full_duplex) — `_enter_chat` refuses on a half-duplex board
        # exactly as `_enter_dropin` does, since an open mic over a speaker that
        # leaks back into the capture would loop on its own TTS. UNTESTED on the
        # dev host — Pi-only (no PortAudio).
        self.chat_active = threading.Event()
        # Effective wake word — the openWakeWord prediction-dict key. Seeded
        # from the sidecar/config here so any early read is safe, then
        # re-resolved authoritatively in `_load_wake_model` (which loads the
        # matching model). Every `pred.get(...)` site reads this, not the raw
        # cfg value, so a dashboard-pushed slug override is honored.
        self._wake_word = _effective_wake_word(cfg)
        # Effective detection threshold (per-word sidecar override else config).
        # Cached like _wake_word; refreshed in _load_wake_model. Every
        # pred.get(...) compares against this, not the raw cfg value.
        self._wake_threshold = _effective_wake_threshold(cfg)
        # Self-upgrade (Feature 10) rollback latch. Set True by the `ready`
        # frame handler once the freshly-upgraded code connects successfully;
        # the post-restart watchdog reads it to decide whether the upgrade
        # took (leave it) or wedged (restore the tarball + bounce).
        self._upgrade_confirmed = False
        # Cap the inbound relay backlog during a call (~0.3 s at 30 ms/frame)
        # so playback latency can't grow unbounded if the consumer falls
        # behind — drop oldest to stay live.
        self._DROPIN_MAX_PLAYBACK_FRAMES = max(4, int(0.3 * 1000 / FRAME_MS))
        # Set when the receiver enqueues at least one audio frame for
        # the current response (cleared on `response_start`). Lets the
        # `response_end` handler distinguish "we have audio still
        # draining out the speakers, defer LED + response_done until
        # the playback thread's close_stream signals drain" from
        # "empty response, drain is instantaneous, release immediately."
        self._response_audio_received = threading.Event()
        # Pre-buffer state. While `_prebuffer_active` is True, the
        # receiver accumulates binary audio frames in `_prebuffer_buffer`
        # instead of pushing them to playback_q — gives the playback
        # thread N seconds of audio cushion before it opens the
        # PortAudio stream, so bursty WS delivery (slow Pi WiFi, busy
        # event loop on the server, anything that makes chunks
        # arrive in fits and starts) doesn't underrun the small default
        # ALSA buffer mid-word.
        self._prebuffer_active = False
        self._prebuffer_buffer: list[bytes] = []
        self._prebuffer_target_bytes = 0
        self._prebuffer_accumulated = 0
        # When `response_end` arrives but audio is still draining, the
        # receiver stashes the post-response LED state here ("listening"
        # for follow-ups, "idle" otherwise) and the playback thread's
        # close_stream applies it after `out_stream.stop()` returns —
        # i.e., when PortAudio has actually clocked the last samples out
        # of the speaker. Without this, the green "speaking" LED ends
        # the moment the server finishes streaming bytes, which
        # is several hundred ms before the user hears the last syllable.
        self._post_playback_state: str | None = None

        # Set during run(). `_async_shutdown` mirrors `shutdown_event` on the
        # asyncio side so the signal handler can interrupt awaits (websocket
        # recv, reconnect sleep) without waiting on a network round-trip.
        self.loop: asyncio.AbstractEventLoop | None = None
        self.ws: websockets.WebSocketClientProtocol | None = None
        self._async_shutdown: asyncio.Event | None = None

        # Set on response_start so the playback thread knows the rate.
        self.audio_sample_rate: int = 16_000

        # Carries voiced frames captured by the barge-in monitor so the
        # next utterance starts with the user's first syllables, not silence.
        self._barge_prefix: list[bytes] = []

        self._input_stream: sd.RawInputStream | None = None
        self._mic_thread: threading.Thread | None = None
        self._playback_thread: threading.Thread | None = None

        # Set whenever the playback thread is NOT holding the output device.
        # Cleared when it opens a stream; re-set when it closes one. The
        # music deferral (_start_music_when_idle) waits on this so mpg123
        # doesn't race PortAudio's internal buffer drain — `out_stream.stop()`
        # blocks until queued audio finishes clocking out, which can be
        # several seconds AFTER playback_q.empty() is true.
        self._playback_idle = threading.Event()
        self._playback_idle.set()  # initially no stream → device is free

        # mpg123 subprocess for music streaming. Spawned on `music_start` text
        # frames from the server, killed on `music_stop`, when the wake
        # word fires (so the mic captures clean audio for the next command),
        # and when TTS playback starts (so TTS isn't competing with music
        # through ALSA — Pi OS Lite has no software mixer).
        self._music_proc: subprocess.Popen | None = None
        self._music_lock = threading.Lock()
        self._music_url: str | None = None

        # mpg123 subprocess for the instant wake-word greeting. Spawned on
        # wake (non-blocking, so it overlaps the command capture — the chip's
        # AEC keeps it out of the mic), stopped when the command-response TTS
        # starts and at the next wake.
        self._greeting_proc: subprocess.Popen | None = None
        self._greeting_lock = threading.Lock()
        # Whether a wake greeting played for the in-flight turn. Sent on
        # utterance_end so the server can strip a greeting that bled
        # past the AEC out of the transcript. Set when a greeting plays,
        # reset when reported (and at the start of each wake decision).
        self._greeting_played_this_turn = False

        # State-indicator LEDs. Backend depends on the device profile:
        # APA102 over SPI on the ReSpeaker HAT, or the WS2812 ring driven
        # via xvf_host on the XVF3800. The controller owns its own worker
        # thread so hardware writes don't compete with the audio threads;
        # set_state() calls are non-blocking — they just signal the worker.
        self._leds = LEDController(LEDConfig(
            enabled=cfg.leds_enabled,
            num_leds=cfg.leds_num,
            brightness=cfg.leds_brightness,
            backend=cfg.device.led_backend,
            xvf_host_path=cfg.leds_xvf_host_path,
        ))

        # WiFi self-heal state. The watcher thread polls
        # `iw dev wlan0 link` every `wifi_poll_interval_sec` and runs
        # `sudo wpa_cli reassociate` when rx bitrate dips below the
        # min-healthy threshold. `_network_degraded` arms when either
        # the reassociate fails to recover OR the WS has been gone past
        # `wifi_degraded_after_disconnect_sec` — the next wake word
        # plays a canned local MP3 instead of trying to stream. Cleared
        # on a healthy rate observation OR on successful WS connect.
        # Defends against the rx-bitrate-stuck-at-1-Mbit/s incident
        # described under [wifi] in config.toml.example.
        self._network_degraded = threading.Event()
        self._ws_disconnected_since: float | None = None
        self._wifi_thread: threading.Thread | None = None

    # ── Mic ingestion ─────────────────────────────────────────────────

    def _start_mic(self) -> None:
        # Capture format depends on the device profile. The HAT codec gives
        # int16; we ask sounddevice for 1 channel and PortAudio downmixes
        # its stereo. The XVF3800 USB firmware is int32, 2-channel
        # (ch0 = Conference, ch1 = ASR beam) — we capture both and SLICE
        # the ASR channel (downmixing it with Conference would corrupt the
        # beamformed stream), then arithmetic-shift the left-justified
        # 32-bit samples down to int16. Either way the rest of the pipeline
        # (raw_q, _frame_dbfs, webrtcvad, openWakeWord) sees 16 kHz mono
        # int16 exactly as before. Buffer size = exactly one VAD frame for
        # predictable timing.
        dev = self.cfg.device
        select = dev.capture_select_channel
        channels = dev.capture_channels
        if select is not None:
            log.info(
                "mic capture: %s %dch, selecting channel %d (ASR beam) → mono int16",
                dev.capture_dtype, channels, select,
            )

        def cb(indata, frames, time_info, status) -> None:  # noqa: ANN001
            if status:
                log.debug("mic status: %s", status)
            if select is None:
                data = bytes(indata)
            else:
                data = devices.select_channel_int16(indata, dev.capture_dtype, channels, select)
            try:
                self.raw_q.put_nowait(data)
            except queue.Full:
                # Consumer (wake-word predict) fell behind realtime.
                # Drop the OLDEST frame to make room for the newest —
                # we'd rather lose two-second-old audio than buffer
                # more lag. See raw_q init for the full rationale.
                try:
                    self.raw_q.get_nowait()
                except queue.Empty:
                    pass
                try:
                    self.raw_q.put_nowait(data)
                except queue.Full:
                    pass  # double-failure; next callback will succeed
                self._raw_q_drops += 1
                now = time.monotonic()
                if now - self._raw_q_last_drop_log > 30.0:
                    log.warning(
                        "mic queue overflowing: %d frames dropped in the "
                        "last 30s. Wake-word predict is falling behind "
                        "realtime — likely thermal throttling, swap, or "
                        "another CPU hog. Wake-word will still fire on "
                        "recent audio (queue is bounded) but you may see "
                        "missed detections.",
                        self._raw_q_drops,
                    )
                    self._raw_q_drops = 0
                    self._raw_q_last_drop_log = now

        self._input_stream = sd.RawInputStream(
            samplerate=SAMPLE_RATE,
            channels=channels,
            dtype=dev.capture_dtype,
            blocksize=FRAME_SAMPLES,
            callback=cb,
            device=self.cfg.input_device,
        )
        self._input_stream.start()

    def _stop_mic(self) -> None:
        if self._input_stream is not None:
            try:
                self._input_stream.stop()
                self._input_stream.close()
            except Exception:
                pass
            self._input_stream = None

    def _drain_mic(self) -> None:
        try:
            while True:
                self.raw_q.get_nowait()
        except queue.Empty:
            pass

    # ── Sender bridge (thread → asyncio) ──────────────────────────────

    def _emit_text(self, payload: dict[str, Any]) -> None:
        if self.loop is None or self.send_q is None:
            return
        self.loop.call_soon_threadsafe(self.send_q.put_nowait, ("text", json.dumps(payload)))

    def _emit_audio(self, frame: bytes) -> None:
        if self.loop is None or self.send_q is None:
            return
        self.loop.call_soon_threadsafe(self.send_q.put_nowait, ("bytes", frame))

    # ── Music streaming ───────────────────────────────────────────────

    def _start_music_when_idle(self, url: str) -> None:
        """Wait until the playback thread releases the ALSA device, then spawn mpg123.

        Pi OS Lite has no software ALSA mixer (see project memory), so the
        satellite's TTS output stream and mpg123 cannot hold the card at the
        same time. The playback thread sets `_playback_idle` AFTER its
        `out_stream.stop()` returns — that's the signal that PortAudio has
        drained its internal buffer and ALSA is genuinely free. Polling on
        `playback_q.empty()` alone is not enough: bytes handed to PortAudio
        keep clocking out for seconds after the queue is empty.

        After mpg123 is up, sleeps `music_prime_sec` to let the ALSA
        devbuffer fill against MPD's always-on silence stream, then
        emits `music_ready` so the server resumes the paused
        queue. Song frames arrive at an already-primed pipeline — no
        first-second underrun stutter.
        """
        if not self._playback_idle.wait(timeout=10.0):
            log.warning("playback thread didn't release output stream in 10s; skipping music")
            return
        if self.shutdown_event.is_set():
            return
        self._start_music(url)
        # Only ack when mpg123 actually came up — if the subprocess
        # spawn failed (mpg123 not installed, immediate crash) there's
        # no point unpausing MPD; the server's fallback timer will
        # resume eventually anyway and the failure logged out of
        # `_start_music` is the diagnostic signal.
        with self._music_lock:
            proc = self._music_proc
            spawned = proc is not None and proc.poll() is None
        if not spawned:
            return
        prime = max(0.0, self.cfg.music_prime_sec)
        if prime > 0.0:
            # Interruptible sleep — a stop/disconnect should cancel
            # the ack so we don't unpause MPD for a session that has
            # already moved on.
            if self.shutdown_event.wait(timeout=prime):
                return
        # Re-check we still own a live subprocess; a `music_stop`
        # that arrived during the prime window will have torn it
        # down. Skipping the ack lets MPD stay paused, which is the
        # correct steady-state for a room nobody is consuming.
        with self._music_lock:
            still_alive = (
                self._music_proc is not None
                and self._music_proc is proc
                and self._music_proc.poll() is None
            )
        if still_alive:
            self._emit_text({"type": "music_ready"})

    def _start_music(self, url: str) -> None:
        """Spawn mpg123 to consume MPD's HTTP stream and play through the HAT.

        mpg123 handles MP3 decode + ALSA output natively — no Python decode
        in the hot path. `-o alsa` is non-optional: on Pi OS Trixie mpg123
        ships with JACK as the default output module, so without `-o alsa`
        it tries to connect to a non-existent JACK server and segfaults.
        `-a` sets the ALSA *device* once the backend is selected.

        Idempotent: a second call with the same URL no-ops; a different URL
        replaces the running subprocess.
        """
        with self._music_lock:
            if self._music_proc is not None and self._music_proc.poll() is None:
                if self._music_url == url:
                    return  # same stream already playing
                self._stop_music_locked()
            log.info("starting music: %s (alsa=%s)", url, self.cfg.music_alsa_device)
            try:
                # Two separate buffers, each guarding against a different
                # source of stutter:
                #   `-b 1024`         — 1 MB pre-buffer between network
                #                       and decoder. ~40 s of MP3 at MPD's
                #                       192 kbps. Absorbs WiFi blips on the
                #                       Pi Zero 2 W's 2.4 GHz radio that
                #                       would otherwise starve the decoder.
                #   `--devbuffer 1.0` — 1 s buffer between decoder and ALSA
                #                       hardware. mpg123's default device
                #                       buffer is tens of ms; on a CPU-
                #                       constrained Pi any GC pause or
                #                       wake-word predict spike longer than
                #                       that drains it and the speakers
                #                       click/glitch. 1 s is comfortably
                #                       beyond any realistic Python hiccup
                #                       and adds imperceptible pause/stop
                #                       latency for music.
                self._music_proc = subprocess.Popen(
                    [
                        "mpg123", "-q",
                        "-b", "1024",
                        "--devbuffer", "1.0",
                        "-o", "alsa",
                        "-a", self.cfg.music_alsa_device,
                        url,
                    ],
                    stdin=subprocess.DEVNULL,
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.PIPE,
                )
                self._music_url = url
                # Watch the subprocess so we surface mpg123 errors instead of
                # leaving a silent zombie when something fails (jack default
                # backend, ALSA device unavailable, stream returns 404, etc.).
                threading.Thread(
                    target=self._music_watch,
                    args=(self._music_proc,),
                    daemon=True,
                    name="music-watch",
                ).start()
                # Lively "music playing" LED look (rainbow on the XVF ring;
                # a no-op on backends without a music state). A wake word or
                # TTS will overwrite this with listening/speaking; the
                # music_stop frame returns the ring to idle.
                self._leds.set_state("music")
            except FileNotFoundError:
                log.error("mpg123 not installed on this Pi (sudo apt install mpg123)")
                self._music_proc = None
                self._music_url = None

    def _music_watch(self, proc: subprocess.Popen) -> None:
        """Reap mpg123 and log its stderr if it exits non-zero."""
        try:
            stderr_bytes = proc.stderr.read() if proc.stderr is not None else b""
        except Exception:
            stderr_bytes = b""
        rc = proc.wait()
        if rc != 0:
            tail = stderr_bytes.decode(errors="replace").strip().splitlines()[-10:]
            log.warning("mpg123 exited rc=%s; stderr tail:\n%s", rc, "\n".join(tail))

    def _is_music_playing(self) -> bool:
        """True if a music mpg123 subprocess is currently running. Checked at
        wake time (before _stop_music) so we can skip the wake greeting while
        music is playing — go straight to listening rather than briefly
        talking over / abruptly interrupting the music with a greeting clip."""
        with self._music_lock:
            return self._music_proc is not None and self._music_proc.poll() is None

    def _stop_music(self) -> None:
        with self._music_lock:
            self._stop_music_locked()

    def _stop_music_locked(self) -> None:
        # Caller holds self._music_lock.
        if self._music_proc is None:
            return
        if self._music_proc.poll() is None:
            log.info("stopping music")
            try:
                self._music_proc.terminate()
                try:
                    self._music_proc.wait(timeout=2.0)
                except subprocess.TimeoutExpired:
                    self._music_proc.kill()
                    self._music_proc.wait(timeout=1.0)
            except Exception as e:
                log.warning("music stop failed: %s", e)
        self._music_proc = None
        self._music_url = None

    # ── Wake-word greeting ─────────────────────────────────────────────

    def _pick_greeting(self) -> Path | None:
        """Choose a random greeting clip, weighting the funny ones by
        ``greeting_funny_chance``. Returns None when the bank is empty."""
        d = _greetings_dir()
        if not d.is_dir():
            return None
        funny = list(d.glob("greet_funny_*.mp3"))
        generic = [p for p in d.glob("greet_*.mp3")
                   if not p.name.startswith("greet_funny_")]
        use_funny = funny and random.random() < self.cfg.greeting_funny_chance
        pool = funny if use_funny else generic
        if not pool:  # one category empty — fall back to the other
            pool = generic or funny
        return random.choice(pool) if pool else None

    def _play_greeting(self) -> None:
        """Play a random greeting through the array, non-blocking, so it
        overlaps the command capture (the chip's AEC keeps it out of the
        mic). Best-effort: disabled, empty bank, or mpg123 missing → skip."""
        if not self.cfg.greeting_enabled:
            return
        clip = self._pick_greeting()
        if clip is None:
            return
        self._stop_greeting()  # never stack two greetings
        with self._greeting_lock:
            try:
                self._greeting_proc = subprocess.Popen(
                    [
                        "mpg123", "-q",
                        *_volume.mpg123_scale_args(self.cfg.tts_playback_gain),
                        "-o", "alsa", "-a", self.cfg.music_alsa_device, str(clip),
                    ],
                    stdin=subprocess.DEVNULL,
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                )
                # Mark the turn so the server strips a greeting that
                # bleeds past the AEC out of the transcript.
                self._greeting_played_this_turn = True
                log.info("greeting: %s", clip.name)
            except FileNotFoundError:
                log.debug("mpg123 not installed; skipping greeting")
                self._greeting_proc = None

    def _stop_greeting(self) -> None:
        with self._greeting_lock:
            proc = self._greeting_proc
            self._greeting_proc = None
        if proc is not None and proc.poll() is None:
            try:
                proc.terminate()
                try:
                    proc.wait(timeout=1.0)
                except subprocess.TimeoutExpired:
                    proc.kill()
            except Exception:
                pass

    async def _sync_sounds(self) -> None:
        """Mirror the server's rendered sound clips into the local
        cache (greetings + canned). Best-effort and non-fatal; the blocking
        HTTP runs in a thread so it doesn't stall the event loop. Called on
        connect and on a `sounds_changed` push from the server."""
        if not self.cfg.sounds_sync_enabled:
            return
        try:
            n = await asyncio.to_thread(
                sound_sync.sync,
                sound_sync.http_base_from_ws(self.cfg.domovoi_url),
                SOUNDS_CACHE_DIR,
                _effective_voice(self.cfg),
            )
            if n:
                log.info("sound sync: %d clip(s) updated from server", n)
        except Exception as e:
            log.warning("sound sync failed (using cached/bundled clips): %s", e)

    # ── Playback ──────────────────────────────────────────────────────

    def _drain_playback_q(self) -> None:
        try:
            while True:
                self.playback_q.get_nowait()
        except queue.Empty:
            pass

    def _flush_prebuffer(self) -> None:
        """Push the receiver-side prebuffer to playback_q in order, then
        deactivate. Idempotent — called when the prebuffer target is hit
        (target accumulated bytes) AND on response_end (force flush for
        short responses that never reached the target). Both code paths
        run in the asyncio receiver coroutine, so no lock needed."""
        if not self._prebuffer_active:
            return
        for chunk in self._prebuffer_buffer:
            self.playback_q.put((self.audio_sample_rate, chunk))
        log.info(
            "prebuffer flushed: %d chunks / %d bytes (~%.2fs of audio at %d Hz)",
            len(self._prebuffer_buffer),
            self._prebuffer_accumulated,
            self._prebuffer_accumulated / max(1, self.audio_sample_rate * 2),
            self.audio_sample_rate,
        )
        self._prebuffer_buffer = []
        self._prebuffer_accumulated = 0
        self._prebuffer_active = False

    def _playback_thread_run(self) -> None:
        # `device_rate` is set on profiles whose output device only accepts
        # a fixed rate (XVF3800 USB UAC). When set, we open the stream once
        # at that rate and resample the server's TTS PCM to it; None keeps
        # the original behavior of opening at whatever rate each response
        # declares (the HAT's plug device resamples for free).
        device_rate = self.cfg.device.playback_sample_rate
        gain = self.cfg.tts_playback_gain  # linear boost for TTS PCM (1.0 = none)
        current_sr: int | None = None   # source (server) rate of the open pipeline
        stream_rate: int | None = None  # rate the device is actually open at
        out_stream: sd.RawOutputStream | None = None
        resampler: StreamingResampler | None = None

        def close_stream() -> None:
            nonlocal out_stream, current_sr, stream_rate, resampler
            if out_stream is not None:
                try:
                    # stop() blocks until PortAudio's internal buffer drains
                    # — the device is genuinely free only after this returns.
                    out_stream.stop()
                    out_stream.close()
                except Exception:
                    pass
                out_stream = None
                current_sr = None
                stream_rate = None
                resampler = None  # a new response gets a fresh filter state
                self._playback_idle.set()
            # If `response_end` deferred its LED + response_done release
            # because audio was still draining, fire it now — `out_stream.stop()`
            # has just blocked until the speaker actually clocked out the
            # last samples, so the user sees green for the full audible
            # duration of the response.
            pending = self._post_playback_state
            if pending is not None:
                self._post_playback_state = None
                if pending == "listening":
                    self._leds.set_state("listening")
                else:
                    self._leds.set_state_unless("listening", "idle")
                self.response_done.set()

        def open_stream(src_sr: int) -> bool:
            """Open the output device for a pipeline sourced at ``src_sr``.
            Returns False if the device couldn't be opened at all — the
            caller then drops the chunk rather than crashing the thread."""
            nonlocal out_stream, current_sr, stream_rate, resampler
            # Leave `latency` unset — PortAudio uses the device's default
            # 'high', well-tested against the HAT's I2S duplex (an explicit
            # latency=0.4 once made TTS chop worse). Server-side
            # sentence pipelining handles the inter-sentence gap.
            rate = src_sr if device_rate is None else device_rate
            try:
                out_stream = sd.RawOutputStream(
                    samplerate=rate, channels=1, dtype="int16",
                    device=self.cfg.output_device,
                )
                out_stream.start()
            except Exception as e:
                if device_rate is None:
                    log.warning("opening output stream at %d Hz failed: %s", rate, e)
                    out_stream = None
                    return False
                # A USB UAC device may reject our preferred rate — fall back
                # to its advertised default and resample to that instead, so
                # a rate mismatch never leaves the assistant silent.
                try:
                    info = sd.query_devices(self.cfg.output_device, "output")
                    rate = int(info["default_samplerate"])
                except Exception:
                    rate = 48_000
                log.warning(
                    "output open at %d Hz failed (%s); falling back to device "
                    "default %d Hz", device_rate, e, rate,
                )
                try:
                    out_stream = sd.RawOutputStream(
                        samplerate=rate, channels=1, dtype="int16",
                        device=self.cfg.output_device,
                    )
                    out_stream.start()
                except Exception as e2:
                    log.warning("output fallback open at %d Hz failed: %s", rate, e2)
                    out_stream = None
                    return False
            stream_rate = rate
            current_sr = src_sr
            resampler = StreamingResampler(src_sr, rate) if rate != src_sr else None
            self._playback_idle.clear()
            if self.dropin_active.is_set():
                # Diagnostic: PortAudio's chosen OUTPUT latency is a prime
                # suspect for the drop-in audio lag (it defaults to 'high').
                try:
                    log.info(
                        "drop-in: output stream open at %d Hz, PortAudio latency=%.3fs",
                        rate, float(out_stream.latency),
                    )
                except Exception:
                    pass
            log.info(
                "opening output stream at %d Hz (src=%d Hz, device=%s%s)",
                rate, src_sr, self.cfg.output_device,
                "" if resampler is None else ", resampling",
            )
            return True

        try:
            # Tracks the last time we logged a "queue drained mid-response"
            # warning, rate-limited so a continuous starvation event
            # doesn't spam the journal at 10 Hz.
            last_starvation_log = 0.0
            while not self.shutdown_event.is_set():
                try:
                    sr, data = self.playback_q.get(timeout=0.1)
                except queue.Empty:
                    # Release the output device while idle so mpg123 (music
                    # playback) can claim it. Pi OS Lite has no software
                    # mixer, so only one process can hold the ALSA card at
                    # a time. We re-open lazily on the next audio chunk.
                    #
                    # EXCEPT during a drop-in: peer audio is intermittent
                    # (gaps when the other side is silent), so releasing the
                    # card between chunks would thrash the device open/closed
                    # for the whole call. Keep it open until the call ends.
                    if (
                        out_stream is not None
                        and not self.playback_active.is_set()
                        and not self.dropin_active.is_set()
                    ):
                        close_stream()
                    elif out_stream is not None and self.playback_active.is_set():
                        # Direct evidence of TTS chop: stream is open,
                        # playback_active is still set (response_end
                        # hasn't arrived), but the queue just ran dry.
                        # PortAudio's internal buffer is going to underrun
                        # any moment. Rate-limit at 1/sec because while
                        # we're starved this branch fires every 100ms.
                        now = time.monotonic()
                        if now - last_starvation_log > 1.0:
                            log.warning(
                                "playback queue drained mid-response — TTS bytes "
                                "arriving slower than playback consumes them. "
                                "Expect audio glitch."
                            )
                            last_starvation_log = now
                    continue

                if self.stop_playback.is_set():
                    self._drain_playback_q()
                    self.stop_playback.clear()
                    continue

                if sr != current_sr:
                    close_stream()
                    if not open_stream(sr):
                        continue  # device unavailable; drop this chunk

                # Resample to the device rate when the profile pins one;
                # `process` may return b"" while the FIR primes on the first
                # chunk (next chunk releases it).
                out = resampler.process(data) if resampler is not None else data
                if not out:
                    continue

                # Make-up gain for quiet TTS, hard-clipped so a peak can't
                # wrap/distort. Done in float to avoid double quantization.
                if gain != 1.0:
                    boosted = np.frombuffer(out, dtype=np.int16).astype(np.float32) * gain
                    out = np.clip(boosted, -32768, 32767).astype(np.int16).tobytes()

                # Slice writes so a barge-in stop has a ~100 ms upper bound
                # on how much queued audio still plays. Granularity is in the
                # OUTPUT (device) rate since `out` is already post-resample.
                slice_bytes = stream_rate * 2 // 10  # 100 ms @ int16 mono
                i = 0
                while i < len(out):
                    if self.stop_playback.is_set() or self.shutdown_event.is_set():
                        break
                    chunk = out[i : i + slice_bytes]
                    try:
                        out_stream.write(chunk)
                    except Exception as e:
                        log.warning("playback write failed: %s", e)
                        break
                    i += slice_bytes
        finally:
            close_stream()

    # ── Noise-gate auto-calibration ────────────────────────────────────

    # Threshold tighter than this would gate out most conversational
    # speech (around -30 dBFS at typical mic distance). Hard-coded
    # because it's a sanity belt against contaminated calibrations,
    # not a knob the user should be tuning.
    _NOISE_GATE_SAFETY_CAP_DBFS = -28.0

    def _derive_threshold(self, samples: list[float]) -> float | None:
        """Compute a noise-gate threshold from a list of frame dBFS values.

        Uses the median — robust against brief speech contamination in
        the sample (e.g., the user said "Hey Jarvis" while the wake
        model was still loading and the calibration window swallowed
        those frames). p95 was the original choice because it tracks
        louder *ambient* noises (HVAC cycles, fridge) but it gets
        fooled by even a 1 second speech outlier in a 5 second sample.
        Periodic recalibration with the 30 s rolling buffer + EWMA
        catches the louder ambient noises over time without
        single-sample fragility.

        Returns None when the result is suspect — too few samples to
        be statistically meaningful, or a derived threshold above
        ``_NOISE_GATE_SAFETY_CAP_DBFS`` (which would silently break
        endpointing). The caller treats None as "skip this round, keep
        the existing threshold."
        """
        finite = [s for s in samples if s != float("-inf")]
        if len(finite) < 50:  # ~1.5 s at 30 ms/frame — too few to trust
            return None
        finite.sort()
        median = finite[len(finite) // 2]
        threshold = median + self.cfg.noise_gate_calibration_margin_db
        if threshold > self._NOISE_GATE_SAFETY_CAP_DBFS:
            return None
        return threshold

    def _sample_ambient_median_dbfs(self, sample_sec: float) -> float:
        """Drain raw_q for ``sample_sec`` of ambient and return the
        median dBFS. Used by the mic-gain auto-tune as its measurement
        callback. Returns -inf if no usable samples arrived."""
        target_count = max(10, int(sample_sec * 1000 / FRAME_MS))
        deadline = time.monotonic() + sample_sec + 1.5
        samples: list[float] = []
        while len(samples) < target_count and time.monotonic() < deadline:
            try:
                frame = self.raw_q.get(timeout=0.1)
            except queue.Empty:
                continue
            if self.shutdown_event.is_set():
                break
            samples.append(_frame_dbfs(frame))
        finite = [s for s in samples if s != float("-inf")]
        if not finite:
            return float("-inf")
        finite.sort()
        return finite[len(finite) // 2]

    def _calibrate_mic_gain_initial(self) -> None:
        """One-time hardware-gain calibration before the noise-gate
        software-threshold calibration.

        Runs first because the noise-gate calibration *trusts* its
        ambient sample to derive the threshold. If hardware mic gain is
        wrong (PGA way too high, ambient at -10 dBFS), the noise-gate
        derivation hits its safety cap and falls back to a default that
        doesn't actually fit the room — and VAD then chews through 100%
        gate-passing frames forever.

        Bisect/interpolate the ALSA PGA Capture Volume until ambient
        lands inside ``mic_gain.target_dbfs ± tolerance_db``. Each
        iteration drains the mic queue (so the new gain shows in the
        sample, not the old buffered frames) and re-samples.

        No-op when ``mic_gain.enabled = false``, when amixer isn't
        installed, or when no recognized capture control exists on the
        configured card. The noise-gate calibration runs anyway.
        """
        if not self.cfg.mic_gain_enabled:
            return
        from satellite.mic_gain import tune_to_target

        def sample() -> float:
            # Drain stale frames first — anything currently in raw_q was
            # captured at the *previous* PGA setting and would skew the
            # next measurement. Then wait briefly so the new gain
            # propagates through sounddevice's input buffer before we
            # start consuming.
            self._drain_mic()
            time.sleep(0.15)
            return self._sample_ambient_median_dbfs(self.cfg.mic_gain_sample_sec)

        try:
            tune_to_target(
                sample_fn=sample,
                card=self.cfg.mic_gain_card,
                control_name=self.cfg.mic_gain_control,
                target_dbfs=self.cfg.mic_gain_target_dbfs,
                tolerance_db=self.cfg.mic_gain_tolerance_db,
                pga_min=self.cfg.mic_gain_pga_min,
                pga_max=self.cfg.mic_gain_pga_max,
            )
        except Exception as e:
            # Audio calibration is best-effort; never break boot.
            log.warning("mic-gain auto-tune raised: %s — continuing", e)

    def _calibrate_noise_gate_initial(self) -> None:
        """One-time calibration on satellite boot.

        Drains a few seconds of ambient audio from the input queue and
        derives the noise-gate threshold from it. Runs in the mic
        thread *while the wake-word model is still loading* — the
        sounddevice callback has been pushing frames into ``raw_q``
        since `_start_mic` was called, so by the time the wake model
        finishes (~10–15 s on Pi Zero 2 W), there's plenty of ambient
        material waiting. We just sample the first few seconds.

        No-op when ``noise_gate.auto_calibrate = false`` in config.
        """
        if not self.cfg.noise_gate_auto_calibrate:
            return

        target_count = int(
            self.cfg.noise_gate_calibration_sample_sec * 1000 / FRAME_MS
        )
        deadline = time.monotonic() + self.cfg.noise_gate_calibration_sample_sec + 2.0
        samples: list[float] = []
        while len(samples) < target_count and time.monotonic() < deadline:
            try:
                frame = self.raw_q.get(timeout=0.1)
            except queue.Empty:
                continue
            if self.shutdown_event.is_set():
                return
            samples.append(_frame_dbfs(frame))

        derived = self._derive_threshold(samples)
        if derived is None:
            # Either too few samples or the result hit the safety cap
            # (sample looked contaminated with speech). Surface the
            # actual stats so the user can tell which case they're in.
            finite = [s for s in samples if s != float("-inf")]
            if finite:
                finite.sort()
                median = finite[len(finite) // 2]
                p95 = finite[int(0.95 * (len(finite) - 1))]
                log.info(
                    "noise gate: boot calibration deferred (median=%.1f "
                    "p95=%.1f + margin %.1f = %.1f dBFS, would-be threshold "
                    "tighter than safety cap %.1f dBFS — sample looks "
                    "contaminated). Keeping default %.1f dBFS until rolling "
                    "recalibration adapts.",
                    median, p95,
                    self.cfg.noise_gate_calibration_margin_db,
                    median + self.cfg.noise_gate_calibration_margin_db,
                    self._NOISE_GATE_SAFETY_CAP_DBFS,
                    self.cfg.noise_gate_dbfs,
                )
            else:
                log.info(
                    "noise gate: boot calibration deferred (only %d "
                    "non-silent samples in window — too few to derive a "
                    "threshold). Keeping default %.1f dBFS.",
                    len(samples), self.cfg.noise_gate_dbfs,
                )
            return
        log.info(
            "noise gate calibrated: %.1f → %.1f dBFS (sampled %d frames)",
            self.cfg.noise_gate_dbfs, derived, len(samples),
        )
        self.cfg.noise_gate_dbfs = derived

    def _maybe_recalibrate(self, samples: list[float]) -> None:
        """Periodic / event-triggered recalibration via EWMA so a
        single transient (one HVAC cycle, a passing motorcycle) doesn't
        slam the threshold to a wildly different value.

        ``new = 0.7 * old + 0.3 * derived``. Reaches steady state in
        ~5 cycles of disagreement, fast enough to track real ambient
        shifts (windows opened, washing machine started, season change)
        without overreacting to single events.
        """
        if not self.cfg.noise_gate_auto_calibrate:
            return
        derived = self._derive_threshold(samples)
        if derived is None:
            return
        old = self.cfg.noise_gate_dbfs
        smoothed = 0.7 * old + 0.3 * derived
        # Only log + apply when the change is meaningful — avoids spam
        # in the journal during steady state.
        if abs(smoothed - old) < 1.0:
            return
        log.info(
            "noise gate auto-tune: %.1f → %.1f dBFS (target derived from %d samples: %.1f)",
            old, smoothed, len(samples), derived,
        )
        self.cfg.noise_gate_dbfs = smoothed

    # ── WiFi self-heal ─────────────────────────────────────────────────

    def _check_wifi_link(self) -> dict[str, Any] | None:
        """Run `iw dev wlan0 link` and parse rx/tx bitrate + SSID.

        Returns ``None`` when iw isn't installed, the call fails, or
        wlan0 isn't associated (link-down case prints "Not connected.").
        Otherwise a dict with rx_mbits / tx_mbits / ssid (any of which
        may be None if that line wasn't present).

        Used by the WiFi watcher and also by the post-reassociate
        re-sample. Both code paths tolerate None — they just skip the
        round and try again on the next tick.
        """
        try:
            result = subprocess.run(
                ["iw", "dev", "wlan0", "link"],
                capture_output=True, text=True, timeout=5.0,
            )
        except FileNotFoundError:
            log.warning("wifi watcher: `iw` not installed; disabling further checks")
            self.cfg.wifi_enabled = False
            return None
        except subprocess.TimeoutExpired:
            log.warning("wifi watcher: `iw dev wlan0 link` timed out")
            return None
        if result.returncode != 0:
            return None
        out = result.stdout
        if "Not connected" in out:
            return {"rx_mbits": None, "tx_mbits": None, "ssid": None}
        rx = _IW_RX_RE.search(out)
        tx = _IW_TX_RE.search(out)
        ssid = _IW_SSID_RE.search(out)
        return {
            "rx_mbits": float(rx.group(1)) if rx else None,
            "tx_mbits": float(tx.group(1)) if tx else None,
            "ssid": ssid.group(1).strip() if ssid else None,
        }

    def _reassociate_wifi(self) -> bool:
        """Run `sudo -n /usr/sbin/wpa_cli -i wlan0 reassociate`.

        Returns True when wpa_cli prints OK. False on any failure —
        sudo prompt (sudoers entry missing or wrong path), wpa_cli
        unavailable, command timeout, non-zero exit. Callers treat
        False as "give up this round, the next watcher tick will
        retry after cooldown."

        Both the autonomous watcher and the voice-triggered path
        ("Hey Jarvis, fix the wifi") call this directly. The watcher
        owns its own cooldown bookkeeping; voice deliberately bypasses
        cooldown — user intent overrides the safety throttle.
        """
        try:
            result = subprocess.run(
                ["sudo", "-n", "/usr/sbin/wpa_cli", "-i", "wlan0", "reassociate"],
                capture_output=True, text=True, timeout=5.0,
            )
        except FileNotFoundError as e:
            log.warning("wpa_cli reassociate: missing binary (%s)", e)
            return False
        except subprocess.TimeoutExpired:
            log.warning("wpa_cli reassociate: timed out after 5s")
            return False
        if result.returncode == 0 and "OK" in result.stdout:
            log.info("wpa_cli reassociate: OK")
            return True
        log.warning(
            "wpa_cli reassociate failed: rc=%d stdout=%r stderr=%r. "
            "Check the sudoers entry from PROVISIONING.md step 6.7 — "
            "`sudo -n /usr/sbin/wpa_cli -i wlan0 reassociate` should "
            "print OK without prompting for a password.",
            result.returncode, result.stdout.strip(), result.stderr.strip(),
        )
        return False

    def _restart_service(self) -> bool:
        """Restart this satellite's own systemd service to apply a config
        change that needs a fresh process (e.g. an audio-device or LED
        change pushed from the web UI).

        Runs `sudo -n /usr/bin/systemctl --no-block restart
        domovoi-satellite.service`. `--no-block` is load-bearing: a plain
        synchronous `systemctl restart` issued from INSIDE the unit being
        restarted shares that unit's cgroup, so systemd can SIGTERM this
        very process mid-job and leave the service stopped. `--no-block`
        hands the job to systemd (PID 1), which finishes the restart even
        after we're killed.

        Returns True when systemctl accepts the job. False on any failure —
        a missing/incorrect sudoers entry (password prompt), missing
        binary, timeout, non-zero exit. The matching sudoers line is in
        `satellite/PROVISIONING.md` (self-restart section).
        """
        try:
            result = subprocess.run(
                ["sudo", "-n", "/usr/bin/systemctl", "--no-block",
                 "restart", "domovoi-satellite.service"],
                capture_output=True, text=True, timeout=10.0,
            )
        except FileNotFoundError as e:
            log.warning("self-restart: missing binary (%s)", e)
            return False
        except subprocess.TimeoutExpired:
            log.warning("self-restart: systemctl timed out after 10s")
            return False
        if result.returncode == 0:
            log.info("self-restart: restart queued — the service will bounce now")
            return True
        log.warning(
            "self-restart failed: rc=%d stdout=%r stderr=%r. Check the "
            "self-restart sudoers entry in PROVISIONING.md — `sudo -n "
            "/usr/bin/systemctl --no-block restart domovoi-satellite.service` "
            "must succeed without prompting for a password.",
            result.returncode, result.stdout.strip(), result.stderr.strip(),
        )
        return False

