    def _load_wake_model(self):  # -> openwakeword.model.Model
        from openwakeword.model import Model as WakeWordModel

        # Resolve the EFFECTIVE wake word + model, honoring the runtime
        # sidecar (a model pushed from the dashboard) over the [wake] config.
        # The openWakeWord prediction dict is keyed by the loaded model's
        # STEM, which the effective wake word MUST match — they derive from
        # the same sidecar slug (or both from cfg) so they can't disagree.
        # Cache the effective wake word once at load: every `pred.get(...)`
        # site reads `self._wake_word`, not the raw cfg value, so a sidecar
        # override is honored without re-reading the file per chunk.
        self._wake_word = _effective_wake_word(self.cfg)
        self._wake_threshold = _effective_wake_threshold(self.cfg)
        model_path = _effective_wake_model_path(self.cfg)

        # Custom-trained model (e.g. "Hey Domovoi") if a path resolved — the
        # openWakeWord prediction key is the model file's stem, which
        # `self._wake_word` must match. Otherwise use the named pre-bundled
        # model and auto-download on first use.
        if model_path:
            log.info(
                "loading custom wake model from %s (wake word %r)",
                model_path, self._wake_word,
            )
            return WakeWordModel(
                wakeword_models=[model_path],
                inference_framework="onnx",
            )
        return WakeWordModel(
            wakeword_models=[self._wake_word],
            inference_framework="onnx",
        )

    def _wait_for_wake(self, oww) -> bool:
        """Block until wake word is heard. Returns False on shutdown.

        While we're here doing nothing useful with the wake predictor's
        cycles, we also keep a rolling buffer of recent frame dBFS so
        the noise-gate threshold can be re-derived periodically without
        a separate sampling pass — cheap continuous adaptation to
        seasonal HVAC, evening TV, etc.
        """
        self._drain_mic()
        # Safety: stop any greeting still playing from the previous turn (the
        # common stop is at response_start; this covers turns that ended
        # without one, e.g. a follow-up timeout).
        self._stop_greeting()
        oww.reset()
        log.info("listening for wake word %r in room %r", self._wake_word, self.cfg.room_id)
        # openwakeword's predict() requires chunks that are multiples of 80 ms
        # (1280 samples at 16 kHz). Mic frames are 30 ms (480 samples), so we
        # batch them into a remainder buffer and call predict() once per
        # 1280-sample slice. Sub-minimum chunks make the model silently
        # return zero-prediction every call.
        OWW_CHUNK = 1280  # 80 ms @ 16 kHz
        pending = np.empty(0, dtype=np.int16)

        # Rolling ambient — capped at ~30 s of frames so the per-cycle
        # derivation runs over a meaningful window without unbounded
        # memory growth. Cap on int math to dodge floating-point creep.
        ambient_samples: list[float] = []
        max_ambient = int(30 * 1000 / FRAME_MS)
        last_recalibrate = time.monotonic()

        while not self.shutdown_event.is_set():
            # A drop-in started while we were idle — bail so the mic thread's
            # outer loop can switch into the open-mic relay loop. The caller
            # re-checks dropin_active before treating this as shutdown.
            if self.dropin_active.is_set():
                return False
            # Conversational chat mode started while we were idle (Feature #8) —
            # bail so the outer loop can switch into `_chat_loop`. The caller
            # re-checks `chat_active` before treating this as shutdown, exactly
            # like the drop-in case.
            if self.chat_active.is_set():
                return False
            # A wake-clip recording started while we were idle (Feature #5) —
            # bail so the outer loop can switch into `_wake_recording_loop`.
            # The caller re-checks `wake_recording` before treating this as
            # shutdown, exactly like the drop-in case.
            if self.wake_recording.is_set():
                return False
            try:
                frame = self.raw_q.get(timeout=0.1)
            except queue.Empty:
                continue

            # Track ambient before doing wake prediction; the latter is
            # CPU-heavy on the Pi Zero 2 W and we don't want a
            # cancellation point between "got frame" and "added to
            # ambient" causing a sample drop.
            ambient_samples.append(_frame_dbfs(frame))
            if len(ambient_samples) > max_ambient:
                ambient_samples = ambient_samples[-max_ambient:]
            now = time.monotonic()
            if now - last_recalibrate > self.cfg.noise_gate_recalibrate_interval_sec:
                self._maybe_recalibrate(ambient_samples)
                last_recalibrate = now

            pending = np.concatenate([pending, np.frombuffer(frame, dtype=np.int16)])
            while pending.size >= OWW_CHUNK:
                chunk, pending = pending[:OWW_CHUNK], pending[OWW_CHUNK:]
                try:
                    pred = oww.predict(chunk)
                except Exception as e:
                    log.warning("wake-word predict failed: %s", e)
                    continue
                if pred.get(self._wake_word, 0.0) > self._wake_threshold:
                    log.info("wake word detected")
                    # Network-degraded short-circuit — when the WS is
                    # genuinely down OR the watcher gave up on a
                    # reassociate, the server round-trip will
                    # fail. Play the canned local MP3 instead of
                    # streaming into the void.
                    #
                    # CRITICAL: re-verify the WS state at the moment
                    # of decision instead of trusting a possibly-stale
                    # `_network_degraded` flag. The flag's set/clear
                    # cadence is loose (60 s wifi poll + async WS
                    # reconnect), so a successful reconnect can leave
                    # the flag set for up to a minute after WS is back.
                    # We were burning users with the canned message
                    # well after the server was reachable again
                    # — see 2026-05-07 user report. The
                    # _ws_disconnected_since timestamp is the
                    # source-of-truth: None == currently connected.
                    if self._network_degraded.is_set():
                        if self._ws_disconnected_since is None:
                            log.info(
                                "network_degraded flag was set but WS "
                                "is currently connected; clearing "
                                "stale flag and proceeding normally"
                            )
                            self._network_degraded.clear()
                        else:
                            log.warning(
                                "wake fired, WS down for %.0fs; "
                                "playing canned MP3 instead of streaming",
                                time.monotonic() - self._ws_disconnected_since,
                            )
                            self._stop_music()
                            self._drain_mic()
                            self._play_canned_mp3(
                                _resolve_sound("network_issues.mp3"), "network-issues"
                            )
                            # Reset the wake model so its internal state
                            # doesn't carry forward the canned playback's
                            # echo as primed wake context.
                            oww.reset()
                            self._drain_mic()
                            continue  # back to listening
                    # Flip the LED to "listening" immediately so the
                    # user gets feedback the moment we detect them —
                    # before the housekeeping below, which can take
                    # hundreds of ms (and up to 3 s if `_stop_music`
                    # has to terminate an actively-streaming mpg123).
                    # The redundant set at the top of `_stream_capture`
                    # is a no-op when state is already "listening".
                    self._leds.set_state("listening")
                    # Note whether music was playing BEFORE stopping it — if
                    # so we skip the wake greeting and go straight to
                    # listening (a greeting clip on top of just-stopped music
                    # is an abrupt interruption).
                    music_was_playing = self._is_music_playing()
                    # Kill any running music so the mic captures the user's
                    # next command cleanly (Pi OS Lite has no software mixer
                    # — music + mic on the same card = garbled transcript).
                    self._stop_music()
                    self._drain_mic()
                    # Instant greeting — plays through the array (and thus the
                    # AEC reference) while capture proceeds, so it acknowledges
                    # the wake word without delaying or contaminating capture.
                    # Done after _stop_music so its mpg123 doesn't race the
                    # music one for the output device. Skipped when music was
                    # playing — straight to listening is less jarring.
                    self._greeting_played_this_turn = False
                    if not music_was_playing:
                        self._play_greeting()
                    oww.reset()
                    return True
        return False

    def _stream_capture(
        self,
        prefix_frames: list[bytes],
        pre_speech_timeout_sec: float | None = None,
    ) -> bool:
        """Stream PCM until VAD silence-timeout. Emits utterance_end on exit.

        Returns False if shutdown was triggered, OR if ``pre_speech_timeout_sec``
        is set and the user didn't start speaking within that window —
        used by the follow-up flow so a "did I get that right?" prompt
        that gets ignored doesn't hold the mic open for the full 30 s
        ``max_record_seconds``.

        Tracks frame dBFS during capture and, if the median ends up
        meaningfully above the calibrated noise gate, emits a
        ``noisy_capture`` control frame instead of ``utterance_end``.
        That tells the server the audio is unlikely to transcribe
        cleanly — the server responds with a stock apology TTS
        and the satellite re-derives its noise gate against the new
        ambient on the way back to wake-word listen.
        """
        self._leds.set_state("listening")
        vad = webrtcvad.Vad(self.cfg.vad_aggressiveness)
        speaking = bool(prefix_frames)
        silent_frames = 0
        silence_limit = int(self.cfg.silence_timeout * 1000 / FRAME_MS)
        max_frames = int(self.cfg.max_record_seconds * 1000 / FRAME_MS)
        pre_speech_limit = (
            int(pre_speech_timeout_sec * 1000 / FRAME_MS)
            if pre_speech_timeout_sec is not None
            else None
        )
        pre_speech_silent = 0
        sent = 0

        # Per-frame loudness — used after the loop for noisy-capture
        # detection and for the stats log so we can debug "why did
        # this capture take 15 seconds" without a packet capture.
        capture_dbfs: list[float] = []
        # How many frames passed the gate (loud=True) and how many of
        # *those* VAD called speech. Difference = "loud enough but VAD
        # rejected it" (background noise the gate let through but VAD
        # didn't classify as voice). Both counts surface in the stats
        # log on capture exit.
        gate_pass_count = 0
        voiced_count = 0

        for f in prefix_frames:
            self._emit_audio(f)
            sent += 1
            capture_dbfs.append(_frame_dbfs(f))

        # Tracks why the capture loop ended; surfaced in the stats log.
        # Default carries through if we exit via the `while` condition
        # going false (max_frames or shutdown_event without speech).
        exit_reason = "max_record_seconds"
        while sent < max_frames and not self.shutdown_event.is_set():
            try:
                frame = self.raw_q.get(timeout=0.1)
            except queue.Empty:
                continue
            self._emit_audio(frame)
            sent += 1
            d = _frame_dbfs(frame)
            capture_dbfs.append(d)
            loud = d >= self.cfg.noise_gate_dbfs
            if loud:
                gate_pass_count += 1
            is_speech = loud and vad.is_speech(frame, SAMPLE_RATE)
            if is_speech:
                speaking = True
                silent_frames = 0
                pre_speech_silent = 0
                voiced_count += 1
            elif speaking:
                silent_frames += 1
                if silent_frames >= silence_limit:
                    exit_reason = "vad_silence_after_speech"
                    break
            elif pre_speech_limit is not None:
                # Follow-up flow: counting up *before* any speech ever
                # arrived. If the bar is reached, the user didn't reply —
                # bail without emitting an utterance_end so the server
                # doesn't try to transcribe pure silence.
                pre_speech_silent += 1
                if pre_speech_silent >= pre_speech_limit:
                    log.info(
                        "follow-up: no reply within timeout, returning "
                        "to wake-word listen (%s)",
                        _capture_stats_str(
                            sent, gate_pass_count, voiced_count,
                            capture_dbfs, self.cfg.noise_gate_dbfs,
                        ),
                    )
                    self._leds.set_state("idle")
                    return False
        if self.shutdown_event.is_set():
            exit_reason = "shutdown"

        if self.shutdown_event.is_set() and not speaking:
            return False

        stats = _capture_stats_str(
            sent, gate_pass_count, voiced_count,
            capture_dbfs, self.cfg.noise_gate_dbfs,
        )

        # Hit max without VAD ever finding silence — the most common
        # symptom of a misconfigured noise gate or wrong VAD level.
        # Bump to WARNING so it stands out in the journal.
        if exit_reason == "max_record_seconds":
            log.warning(
                "capture: hit max_record_seconds (%ds) without VAD ever "
                "finding silence — endpointing failed. %s. Likely cause: "
                "gate too tight (no frames pass) or VAD aggressiveness "
                "too low (background noise scoring as speech).",
                int(self.cfg.max_record_seconds), stats,
            )
        else:
            log.info("capture ended (%s): %s", exit_reason, stats)

        # Noisy-capture detection: only fire when the audio is genuinely
        # saturated (clipping-adjacent), not whenever speech happens to
        # be louder than the noise gate. An earlier draft compared
        # median against `gate + N dB` and false-positived on every
        # successful capture, because speech naturally sits 20+ dB
        # above the gate. The absolute-floor signal triggers only when
        # the audio is so loud Whisper genuinely can't transcribe it —
        # rare in practice, exactly the case the user-facing apology
        # is meant for.
        if (
            self.cfg.noise_gate_auto_calibrate
            and len(capture_dbfs) >= 30  # ~1 s, otherwise too small a sample
        ):
            finite = [d for d in capture_dbfs if d != float("-inf")]
            if finite:
                finite.sort()
                median = finite[len(finite) // 2]
                if median > self.cfg.noise_gate_noisy_capture_dbfs:
                    log.info(
                        "noisy capture detected: median %.1f dBFS exceeds "
                        "saturation floor %.1f dBFS; asking user to retry "
                        "and recalibrating",
                        median,
                        self.cfg.noise_gate_noisy_capture_dbfs,
                    )
                    self._maybe_recalibrate(capture_dbfs)
                    self._leds.set_state("error")
                    self._emit_text({"type": "noisy_capture"})
                    return True  # successful exit, just via the noisy path

        self._leds.set_state("thinking")
        self._emit_text({
            "type": "utterance_end",
            "greeting_played": self._greeting_played_this_turn,
        })
        # One-shot: only this turn's transcript should be greeting-filtered.
        self._greeting_played_this_turn = False
        return True

    def _await_response_with_barge(self, oww) -> str:
        """Wait for response_end, monitoring for barge-in during playback.

        Returns: 'done' | 'barge' | 'shutdown'.
        On 'barge', `_barge_prefix` holds the recent voiced frames to carry
        into the next capture (empty in wake-word mode — user said the wake
        word, not the actual command, so there's nothing to carry).
        """
        if self.cfg.barge_in_require_wake_word:
            return self._await_response_with_wake_barge(oww)

        vad = webrtcvad.Vad(self.cfg.vad_aggressiveness_during_tts)
        required = max(1, self.cfg.barge_in_min_speech_ms // FRAME_MS)
        recent: deque[bytes] = deque(maxlen=required + 5)
        voiced = 0

        while not self.shutdown_event.is_set():
            if self.response_done.is_set():
                log.debug("response_done set; returning to wake-word listen")
                return "done"
            try:
                frame = self.raw_q.get(timeout=0.1)
            except queue.Empty:
                continue

            # Only barge while audio is actually playing — barging during STT
            # would cancel a response the user is about to hear.
            #
            # Stay armed through the deferred-drain tail: response_end clears
            # playback_active the instant the audio bytes are queued, but a
            # short single-sentence reply is still audibly draining out the
            # speaker after that. _playback_idle is set only once the speaker
            # has actually drained (close_stream → out_stream.stop()), so gate
            # on both — otherwise short responses play entirely in the disarmed
            # window and can't be interrupted at all.
            if not self.cfg.barge_in or (
                not self.playback_active.is_set() and self._playback_idle.is_set()
            ):
                # Reset the rolling state so we don't trigger on stale frames
                # the moment playback starts.
                voiced = 0
                recent.clear()
                continue

            recent.append(frame)
            loud = _frame_dbfs(frame) >= self.cfg.noise_gate_dbfs
            if loud and vad.is_speech(frame, SAMPLE_RATE):
                voiced += 1
                if voiced >= required:
                    log.info("barge-in detected")
                    self._emit_text({"type": "barge_in"})
                    self.stop_playback.set()
                    self._drain_playback_q()
                    self._emit_text({"type": "utterance_start", "trigger": "barge_in"})
                    self._barge_prefix = list(recent)
                    return "barge"
            else:
                voiced = max(0, voiced - 1)

        return "shutdown"

    def _await_response_with_wake_barge(self, oww) -> str:
        """Wake-word-gated barge: only the wake word interrupts playback.

        Immune to speaker echo and arbitrary background speech, at the cost
        of a slightly less natural interruption flow (user must say "hey
        jarvis stop" rather than just speak over the response).
        """
        OWW_CHUNK = 1280  # 80 ms @ 16 kHz — see _wait_for_wake
        pending = np.empty(0, dtype=np.int16)
        primed = False

        while not self.shutdown_event.is_set():
            if self.response_done.is_set():
                return "done"
            try:
                frame = self.raw_q.get(timeout=0.1)
            except queue.Empty:
                continue

            # Stay armed through the deferred-drain tail (see the VAD-barge
            # monitor above) — short replies finish playing after response_end
            # clears playback_active, so also accept "audio still draining".
            if not self.cfg.barge_in or (
                not self.playback_active.is_set() and self._playback_idle.is_set()
            ):
                pending = np.empty(0, dtype=np.int16)
                primed = False
                continue

            # Reset the wake model the first time playback starts so we
            # don't carry residual state from the previous detection into
            # the new monitoring window.
            if not primed:
                oww.reset()
                primed = True

            pending = np.concatenate([pending, np.frombuffer(frame, dtype=np.int16)])
            while pending.size >= OWW_CHUNK:
                chunk, pending = pending[:OWW_CHUNK], pending[OWW_CHUNK:]
                try:
                    pred = oww.predict(chunk)
                except Exception as e:
                    log.warning("wake-barge predict failed: %s", e)
                    continue
                if pred.get(self._wake_word, 0.0) > self._wake_threshold:
                    log.info("barge-in detected (wake word)")
                    self._emit_text({"type": "barge_in"})
                    self.stop_playback.set()
                    self._drain_playback_q()
                    self._emit_text({"type": "utterance_start", "trigger": "barge_in"})
                    self._barge_prefix = []
                    return "barge"

        return "shutdown"

    # ── Two-way drop-in / open-mic (Feature 4) ────────────────────────────
    # NOTE: this whole path is UNTESTED on the dev host — it needs real
    # PortAudio/ALSA + an XVF3800 (on-chip AEC) satellite; verify it on
    # hardware after changes.

    def _enter_dropin(self, payload: dict[str, Any]) -> None:
        """Receiver-side: handle a `dropin_start` frame — enter open-mic mode.

        Runs on the asyncio receiver thread; it only flips flags + stops
        music. The mic thread (which watches `dropin_active`) does the actual
        continuous streaming in `_dropin_loop`.
        """
        peer = payload.get("peer_room")
        rate = int(payload.get("audio_sample_rate") or 16_000)
        full_duplex = bool(payload.get("full_duplex", False))
        # Defence in depth: the server already gates on AEC, but never
        # open the mic-while-playing on a board that would howl.
        if not full_duplex or not self.cfg.device.supports_full_duplex:
            log.warning("dropin_start refused: room lacks full-duplex AEC")
            self._emit_text({"type": "dropin_end"})
            return
        log.info("drop-in started with %r (inbound rate=%d Hz)", peer, rate)
        # The call owns the output device — stop music + any wake greeting.
        self._stop_music()
        self._stop_greeting()
        # Inbound relay PCM is 16 kHz, NOT the last TTS rate. Pin it so the
        # playback thread doesn't pitch it wrong, and disarm the TTS
        # prebuffer (relay audio plays through immediately).
        self._dropin_rate = rate
        self.audio_sample_rate = rate
        self._prebuffer_active = False
        self.stop_playback.clear()
        self._playback_idle.clear()
        self.dropin_active.set()
        # Cancel any deferred post-playback LED transition left by the
        # initiator's own "dropping in…" TTS. Without this, close_stream()
        # fires the stashed "idle" once that audio finishes draining and
        # clobbers the red on the caller side (the target never spoke a turn,
        # so it isn't affected — which is why only the caller lost the red).
        # Release response_done directly too, so the initiator's mic thread
        # leaves _await_response_with_barge and enters the open-mic loop
        # without waiting on that same drain.
        self._post_playback_state = None
        self.response_done.set()
        # Solid red while the call is live.
        self._leds.set_state("dropin")

    def _exit_dropin(self, payload: dict[str, Any]) -> None:
        """Receiver-side: handle a `dropin_end` frame — leave open-mic mode."""
        if not self.dropin_active.is_set():
            return
        log.info("drop-in ended (reason=%s)", payload.get("reason"))
        self.dropin_active.clear()
        # Do NOT force-drain: the server streams a short "disconnected"
        # chime just before this frame, and we want it to play out as the call
        # closes. With dropin_active now clear, the playback thread releases
        # the ALSA card once the queue empties (the chime + any sub-100 ms
        # relay tail). The server sends a fresh music_start after this if
        # the room had music suppressed, so we don't resume it here.
        self._leds.set_state("idle")

    # ── Conversational chat mode (Feature #8) ─────────────────────────────

    def _enter_chat(self, payload: dict[str, Any]) -> None:
        """Receiver-side: handle a `chat_start` frame — enter conversational
        chat mode.

        Runs on the asyncio receiver thread; it only flips the `chat_active`
        Event + stops music/greeting (the call owns the output device). The mic
        thread, which watches `chat_active` in its outer loop, runs the actual
        turn loop in `_chat_loop`. This mirrors `_enter_dropin` exactly — same
        receiver→mic hand-off — but for an STT→Letta→TTS conversation rather
        than a peer relay.

        Defence in depth on AEC: the server already gates chat mode on
        settings.chat_mode_enabled AND this room's full-duplex flag (sent in the
        hello frame), but we re-check `supports_full_duplex` here so we never
        open the mic-while-the-speaker-plays on a board without on-chip AEC —
        on a half-duplex board Domovoi's own spoken reply would leak into the
        next open-mic capture and the conversation would talk to itself. On a
        refusal we send `chat_end` straight back so the server tears the mode
        down on its side too, exactly as `_enter_dropin` does.
        """
        if self.dropin_active.is_set() or self.wake_recording.is_set():
            # The three open-mic sub-modes share one mic thread and are mutually
            # exclusive. An out-of-order chat_start while a drop-in or wake
            # recording is live is refused so the sub-mode state can't desync.
            log.warning("chat_start refused: another open-mic mode is already active")
            self._emit_text({"type": "chat_end", "reason": "busy"})
            return
        if not self.cfg.device.supports_full_duplex:
            log.warning(
                "chat_start refused: this board lacks full-duplex AEC; "
                "an open-mic conversation would capture its own TTS"
            )
            self._emit_text({"type": "chat_end", "reason": "no_aec"})
            return
        log.info("conversational chat mode started")
        # The conversation owns the output device — stop any music + the wake
        # greeting so the first turn captures clean speech.
        self._stop_music()
        self._stop_greeting()
        # Arm the mode. The mic thread switches into `_chat_loop` on its next
        # outer-loop tick (and `_wait_for_wake` bails immediately if it's idle
        # there). The normal turn machinery inside `_chat_loop` manages
        # audio_sample_rate / the TTS prebuffer per turn via the usual
        # response_start/response_end frames, so we don't pin a relay rate the
        # way drop-in does.
        self.stop_playback.clear()
        self.chat_active.set()
        # Blue "listening" while we wait for the user to speak the first turn.
        # There's no dedicated chat LED state in leds.py (which this agent does
        # not own); "listening" is the honest existing state for "open mic, your
        # turn", and the per-turn machinery already drives
        # listening→thinking→speaking through the normal capture/response LED
        # transitions, so the ring tracks each turn just like a wake-gated one.
        self._leds.set_state("listening")

    def _exit_chat(self, payload: dict[str, Any]) -> None:
        """Receiver-side: handle a `chat_end` frame — leave conversational
        chat mode.

        Idempotent like `_exit_dropin`. Clears `chat_active`, which breaks the
        mic thread out of `_chat_loop` on its next check; the loop falls back to
        wake-word listening. We do NOT force-drain — the server speaks a short
        goodbye ("talk to you later") just before this frame and we want it to
        play out; the playback thread releases the card once its queue empties.
        """
        if not self.chat_active.is_set():
            return
        log.info("conversational chat mode ended (reason=%s)", payload.get("reason"))
        self.chat_active.clear()
        self._leds.set_state("idle")

    def _chat_loop(self, oww) -> None:
        """Mic-thread loop for a conversational chat session (Feature #8).

        The KEY difference from `_dropin_loop`: chat audio is a NORMAL turn —
        STT → Letta → TTS — NOT a peer relay. So instead of streaming every
        frame raw, each iteration runs ONE capture+respond turn using the exact
        methods the wake-gated loop uses (`_stream_capture` to VAD-segment the
        user's utterance into utterance_start/PCM/utterance_end, then
        `_await_response_with_barge` to play the TTS reply with barge-in) — just
        WITHOUT the wake-word gate in front. The user can keep talking turn
        after turn; only an exit phrase ends it.

        Mode teardown is SERVER-driven: the server routes each
        conversational utterance to Letta, and on an exit phrase ("that's all",
        "stop", "never mind", "thanks goodbye") it clears conversational_mode,
        speaks a goodbye, and sends a `chat_end` frame. `_exit_chat` clears
        `chat_active`, which is what breaks this loop. So this loop never
        decides on its own to end — it just keeps running turns until the flag
        clears (chat_end, or shutdown).

        Reuse rationale: a chat turn is structurally identical to a wake-gated
        turn minus the wake word, so we reuse the inner-loop body of
        `_mic_thread_run` verbatim (the same response_done/playback_active/
        stop_playback/expect_followup reset, the same `_stream_capture` +
        `_await_response_with_barge` pair, the same barge-prefix carry). Unlike
        `_dropin_loop` we DON'T offload wake detection to a side thread: there's
        no always-on relay competing for `oww`, and `_await_response_with_barge`
        can use `oww` for wake-gated barge-in normally if the config asks for it.

        UNTESTED on the dev host — Pi-only (no PortAudio / no AEC array here).
        """
        log.info("entering conversational chat loop")
        self._drain_mic()
        try:
            # `prefix` carries barge-in audio between turns; `pre_speech_timeout`
            # caps how long an idle open mic waits before re-prompting — reuse
            # the follow-up timeout so a silent user doesn't hold the mic open
            # for the full max_record_seconds every turn. The server ends the
            # session on an exit phrase, not on silence, so a timed-out turn
            # just loops back to another open-mic capture (still no wake word).
            prefix: list[bytes] = []
            pre_speech_timeout: float | None = self.cfg.followup_pre_speech_timeout
            while self.chat_active.is_set() and not self.shutdown_event.is_set():
                self.response_done.clear()
                self.playback_active.clear()
                self.stop_playback.clear()
                self.expect_followup.clear()
                self._barge_prefix = []
                # Open mic, no wake gate — the whole point of chat mode. LED
                # back to blue so each new turn reads as "your turn".
                self._leds.set_state("listening")
                self._emit_text({"type": "utterance_start", "trigger": "chat"})

                if not self._stream_capture(prefix, pre_speech_timeout_sec=pre_speech_timeout):
                    if self.shutdown_event.is_set():
                        return
                    # Pre-speech timeout (user went quiet) — _stream_capture
                    # already returned without emitting utterance_end, so the
                    # server has nothing to transcribe. Loop back to another
                    # open-mic capture; the session ends only via chat_end.
                    prefix = []
                    pre_speech_timeout = self.cfg.followup_pre_speech_timeout
                    continue

                outcome = self._await_response_with_barge(oww)
                if outcome == "shutdown":
                    return
                if outcome == "barge":
                    # User talked over the reply — carry the barge audio into the
                    # next capture and use the normal post-speech VAD logic
                    # (no pre-speech timeout, the user is mid-utterance).
                    prefix = self._barge_prefix
                    pre_speech_timeout = None
                    continue
                # outcome == "done": the reply finished. If chat_active is still
                # set, the turn wasn't an exit phrase (the server didn't send
                # chat_end), so loop into the next open-mic turn.
                prefix = []
                pre_speech_timeout = self.cfg.followup_pre_speech_timeout
        finally:
            self._drain_mic()
        log.info("exiting conversational chat loop")

    def _dropin_loop(self, oww) -> None:
        """Mic-thread open-mic loop for a live drop-in.

        The hot path does ONLY ``raw_q.get → _emit_audio`` so the peer hears
        us live. Wake detection runs on a SEPARATE thread
        (``_dropin_wake_watch``) fed by a small drop-oldest queue, because
        ``oww.predict()`` can't keep up with realtime on a Pi Zero 2 W —
        running it inline backs up the bounded mic queue and the relay reads
        seconds-stale audio (the latency bug from first testing). predict
        releases the GIL during inference, so it runs concurrently without
        blocking this loop, and it's best-effort: it drops frames rather than
        ever delaying the relay.

        On a wake-word hit (for "hang up") we hand the next utterance to the
        normal VAD capture/route path: the server stops relaying for that
        utterance, transcribes it, and DropInHandler ends the call on "hang
        up". We deliberately do NOT call ``_await_response_with_barge`` during
        the command turn — that uses ``oww``, which the watcher thread owns
        for the duration of the call.

        UNTESTED — Pi-only (see the class comment above).
        """
        log.info("entering drop-in open-mic loop")
        self._drain_mic()
        # Re-assert solid red: on the initiator, the just-drained "dropping
        # in…" TTS may have run close_stream() and reset the LED after
        # _enter_dropin set it. (We also null _post_playback_state in
        # _enter_dropin; this is belt-and-suspenders so the call is always red.)
        self._leds.set_state("dropin")
        wake_q: queue.Queue[bytes] = queue.Queue(maxsize=max(8, int(1000 / FRAME_MS)))
        wake_detected = threading.Event()
        stop_wake = threading.Event()
        watcher = threading.Thread(
            target=self._dropin_wake_watch,
            args=(oww, wake_q, wake_detected, stop_wake),
            daemon=True, name="dropin-wake",
        )
        watcher.start()
        last_diag = time.monotonic()
        try:
            while self.dropin_active.is_set() and not self.shutdown_event.is_set():
                try:
                    frame = self.raw_q.get(timeout=0.1)
                except queue.Empty:
                    continue

                # Realtime relay — the ONLY work on the hot path.
                self._emit_audio(frame)

                # Diagnostic: which queue (if any) backs up tells us where the
                # latency lives — raw_q (our send side) vs playback_q (peer
                # audio consume side). Logged every ~2 s during a call.
                now = time.monotonic()
                if now - last_diag >= 2.0:
                    last_diag = now
                    sq = self.send_q.qsize() if self.send_q is not None else -1
                    # DEBUG: this confirmed the latency was playback_q growth.
                    # Kept at debug so it's available if lag ever regresses
                    # without spamming the journal every 2 s during normal calls.
                    log.debug(
                        "drop-in queues: raw_q=%d send_q=%d playback_q=%d wake_q=%d",
                        self.raw_q.qsize(), sq, self.playback_q.qsize(), wake_q.qsize(),
                    )

                # Feed the wake detector best-effort; drop oldest if it's behind.
                try:
                    wake_q.put_nowait(frame)
                except queue.Full:
                    try:
                        wake_q.get_nowait()
                        wake_q.put_nowait(frame)
                    except queue.Empty:
                        pass

                if not wake_detected.is_set():
                    continue
                wake_detected.clear()
                log.info("wake word during drop-in — capturing command (e.g. 'hang up')")
                self._emit_text({"type": "utterance_start", "trigger": "wake_word"})
                self.response_done.clear()
                self.stop_playback.clear()
                self.expect_followup.clear()
                self._barge_prefix = []
                self._stream_capture([])
                # Wait for the server's reply ("Hanging up." etc.) or the call
                # to end. A hang-up sends dropin_end → dropin_active clears →
                # this loop exits on the next check.
                while (
                    self.dropin_active.is_set()
                    and not self.response_done.is_set()
                    and not self.shutdown_event.is_set()
                ):
                    time.sleep(0.05)
                if self.dropin_active.is_set():
                    # Call continues (command wasn't a hang-up). The command's
                    # response_start moved audio_sample_rate to the TTS rate —
                    # restore the 16 kHz relay rate, disarm the prebuffer, and
                    # clear the residual wake feed so the just-said wake word
                    # doesn't immediately re-trigger.
                    self.audio_sample_rate = self._dropin_rate
                    self._prebuffer_active = False
                    self._drain_mic()
                    try:
                        while True:
                            wake_q.get_nowait()
                    except queue.Empty:
                        pass
                    wake_detected.clear()
        finally:
            stop_wake.set()
            watcher.join(timeout=1.0)
        log.info("exiting drop-in open-mic loop")

    def _dropin_wake_watch(self, oww, wake_q, detected, stop) -> None:
        """Best-effort wake-word detection during a drop-in, on its own thread.

        Consumes the relay loop's drop-oldest feed and runs ``oww.predict`` on
        1280-sample chunks. Bounds its own backlog so a slow predict never
        builds latency here — missing a few chunks only slightly lowers wake
        sensitivity; it NEVER affects the realtime relay. Sets ``detected`` on
        a hit. Owns ``oww`` exclusively for the call (no other thread touches
        it while a drop-in is live). UNTESTED — Pi-only."""
        OWW_CHUNK = 1280  # 80 ms @ 16 kHz — see _wait_for_wake
        MAX_PENDING = OWW_CHUNK * 8  # ~0.64 s — bound the backlog
        pending = np.empty(0, dtype=np.int16)
        try:
            oww.reset()
        except Exception:
            pass
        while not stop.is_set() and not self.shutdown_event.is_set():
            try:
                frame = wake_q.get(timeout=0.1)
            except queue.Empty:
                continue
            pending = np.concatenate([pending, np.frombuffer(frame, dtype=np.int16)])
            if pending.size > MAX_PENDING:
                pending = pending[-MAX_PENDING:]
            while pending.size >= OWW_CHUNK:
                chunk, pending = pending[:OWW_CHUNK], pending[OWW_CHUNK:]
                try:
                    pred = oww.predict(chunk)
                except Exception as e:
                    log.warning("drop-in wake predict failed: %s", e)
                    continue
                if pred.get(self._wake_word, 0.0) > self._wake_threshold:
                    detected.set()
                    return

    # ── Wake-word training: clip recording + model switch (Feature #5) ──

    def _enter_wake_recording(self, payload: dict[str, Any]) -> None:
        """Receiver-side: handle a `start_wake_recording` frame.

        Runs on the asyncio receiver thread; it only stashes the params + sets
        the `wake_recording` Event. The mic thread (which watches the Event in
        its outer loop) does the actual capture in `_wake_recording_loop`,
        exactly as `_enter_dropin` hands the streaming off to `_dropin_loop`.
        Recording SUSPENDS the wake loop — `_wait_for_wake` bails when the
        Event is set so the mic thread can switch modes without a second
        raw_q consumer.
        """
        slug = payload.get("slug")
        if not slug:
            log.warning("start_wake_recording: no slug in payload; ignoring")
            return
        self._wake_rec_params = {
            "slug": str(slug),
            "clip_seconds": float(payload.get("clip_seconds") or 2.0),
            "target_count": int(payload.get("target_count") or 30),
            "wake_word_id": payload.get("wake_word_id"),
        }
        log.info(
            "wake recording requested: slug=%r %d clips x %.1fs",
            self._wake_rec_params["slug"],
            self._wake_rec_params["target_count"],
            self._wake_rec_params["clip_seconds"],
        )
        # Stop music / greeting so the clips capture clean speech, then arm.
        self._stop_music()
        self._stop_greeting()
        self.wake_recording.set()

    def _wake_recording_loop(self) -> None:
        """Mic-thread loop that records N positive wake-word clips.

        Captures `target_count` clips of `clip_seconds` each from raw_q and
        streams each to the server as
        ``utterance_start(trigger='wake_clip')`` → PCM frames → ``utterance_end``.
        The server-side branch on the `wake_clip` trigger writes a 16 kHz mono
        int16 WAV per clip and bumps the clip count INSTEAD of transcribing /
        routing — so this loop deliberately reuses the normal
        `_emit_audio`/control-frame path but never waits on a response.

        Single mic consumer: this DISPLACES the wake loop while
        `wake_recording` is set (set/cleared by the receiver thread), so raw_q
        is never read by two consumers at once. A `stop_wake_recording` frame
        clears the Event; we also stop after `target_count` clips. UNTESTED —
        Pi-only (no PortAudio on the dev host)."""
        params = self._wake_rec_params or {}
        slug = params.get("slug", "")
        clip_seconds = float(params.get("clip_seconds") or 2.0)
        target = int(params.get("target_count") or 30)
        # 480-sample (30 ms) frames; round up so a clip is at least clip_seconds.
        frames_per_clip = max(1, int(round(clip_seconds * 1000 / FRAME_MS)))
        log.info(
            "entering wake-recording loop: slug=%r %d clips x %d frames",
            slug, target, frames_per_clip,
        )
        self._drain_mic()
        recorded = 0
        try:
            for _ in range(target):
                if not self.wake_recording.is_set() or self.shutdown_event.is_set():
                    break
                # Visual cue that we're recording this clip.
                self._leds.set_state("listening")
                buf: list[bytes] = []
                while (
                    len(buf) < frames_per_clip
                    and self.wake_recording.is_set()
                    and not self.shutdown_event.is_set()
                ):
                    try:
                        frame = self.raw_q.get(timeout=0.1)
                    except queue.Empty:
                        continue
                    buf.append(frame)
                if not buf or not self.wake_recording.is_set():
                    # Stopped mid-clip (or shutdown) — don't emit a partial.
                    break
                # Stream the clip: start marker (trigger flags it as a training
                # clip server-side), the PCM frames, then the end marker. The
                # server writes a WAV per clip; we never wait on a response.
                self._emit_text({"type": "utterance_start", "trigger": "wake_clip"})
                for frame in buf:
                    self._emit_audio(frame)
                self._emit_text({"type": "utterance_end", "greeting_played": False})
                recorded += 1
                log.info("wake clip %d/%d sent (slug=%r)", recorded, target, slug)
                # Brief pause between clips so the user can reset / vary tone,
                # and so the server's per-clip WAV write settles. Interruptible
                # via shutdown so a stop doesn't hang here.
                self._leds.set_state("idle")
                if self.shutdown_event.wait(0.6):
                    break
        finally:
            self.wake_recording.clear()
            self._wake_rec_params = None
            self._drain_mic()
            self._leds.set_state_unless("listening", "idle")
        log.info("exiting wake-recording loop: %d/%d clips sent", recorded, target)

    def _apply_wake_switch(self, slug: str | None, threshold: float | None = None) -> None:
        """Persist a wake-model switch (a model pushed from the dashboard) so
        it survives restarts, mirror the model into the local cache, then
        restart the service to load it. ``threshold`` (the registry word's
        per-word detection threshold) is persisted alongside so the rebooted
        process compares scores against it instead of the [wake] config value.

        Writing the slug to WAKE_SIDECAR makes `_effective_wake_word` /
        `_effective_wake_model_path` resolve to ``<slug>`` + ``<slug>.onnx`` on
        the next boot. We RESTART rather than hot-reload the wake model:
        swapping the openWakeWord model mid-run while the mic thread is inside
        `_wait_for_wake`/`_dropin_loop` (which hold the model handle) is racy.
        A clean restart re-runs `_load_wake_model` with the new sidecar. (A
        safe hot-reload is a deferred enhancement.) Mirrors
        `_apply_voice_switch`, which persists + re-reports without a restart
        because a voice change needs no model reload."""
        if not slug:
            log.warning("set_wake_word: no slug provided; ignoring")
            return
        try:
            WAKE_SIDECAR.parent.mkdir(parents=True, exist_ok=True)
            WAKE_SIDECAR.write_text(slug.strip() + "\n", encoding="utf-8")
            if threshold is not None:
                WAKE_THRESHOLD_SIDECAR.write_text(f"{float(threshold)}\n", encoding="utf-8")
            log.info("set_wake_word: switching to %r (restart to apply)", slug)
        except (OSError, ValueError) as e:
            log.warning("set_wake_word: could not persist %r: %s", slug, e)
            return
        # Pull the matching <slug>.onnx into the cache BEFORE restarting, so
        # the freshly-booted process finds it and doesn't fall back to the
        # config wake word (which would silently never fire on this slug).
        self._sync_wake_models()
        self._restart_service()

    def _sync_wake_models(self) -> None:
        """Mirror the server's trained wake models into the local cache.
        Best-effort and non-fatal — on any failure we keep whatever models are
        already cached. Called when a `set_wake_word` push lands (so the new
        model is present before the restart) and on a `wake_models_changed`
        frame (a model was re-trained / removed). Blocking HTTP; callers run it
        on a worker thread (the switch path) or accept the brief stall (the
        changed-frame path is rare and small)."""
        try:
            n = wake_model_sync.sync(
                sound_sync.http_base_from_ws(self.cfg.domovoi_url),
                WAKE_MODELS_DIR,
            )
            if n:
                log.info("wake-model sync: %d model file(s) updated", n)
        except Exception as e:
            log.warning("wake-model sync failed (using cached models): %s", e)

    def _mic_thread_run(self) -> None:
        try:
            oww = self._load_wake_model()
        except Exception as e:
            log.error("failed to load wake-word model %r: %s", self._wake_word, e)
            self.shutdown_event.set()
            return

        # Boot-time calibration. Mic gain (hardware ALSA PGA) runs
        # FIRST so the noise-gate calibration that follows sees properly-
        # leveled ambient instead of bailing on a contaminated sample.
        # Sounddevice has been buffering frames into raw_q since
        # `_start_mic` ran (well before the wake-word model finished
        # loading), so we have plenty of material; mic-gain explicitly
        # drains and re-samples between PGA changes so its measurements
        # reflect the new setting rather than stale buffered frames.
        self._calibrate_mic_gain_initial()
        self._calibrate_noise_gate_initial()

        while not self.shutdown_event.is_set():
            # Wake-clip recording (Feature #5): the dashboard asked this
            # satellite to record positive training clips. It SUSPENDS the
            # normal wake→capture cycle — a single mic thread owns raw_q, so
            # recording runs INSTEAD OF wake listening, not alongside it.
            # Checked before the drop-in branch since both are mutually
            # exclusive open-mic sub-modes and the server never starts both.
            if self.wake_recording.is_set():
                self._wake_recording_loop()
                continue
            # Drop-in (Feature 4): a live call supersedes the wake→capture
            # cycle. Run the open-mic relay loop until the call ends, then
            # fall back to wake-word listening.
            if self.dropin_active.is_set():
                self._dropin_loop(oww)
                continue
            # Conversational chat mode (Feature #8): a Letta-backed open-mic
            # conversation. Like drop-in it suspends the wake→capture cycle, but
            # each iteration is a NORMAL STT→Letta→TTS turn minus the wake word
            # (not a peer relay). Runs until the server sends `chat_end` on an
            # exit phrase, then falls back to wake-word listening.
            if self.chat_active.is_set():
                self._chat_loop(oww)
                continue
            woke = self._wait_for_wake(oww)
            # _wait_for_wake returns False on BOTH shutdown and "a drop-in /
            # chat / wake-recording just started". Distinguish: if any mode is
            # now active, loop back to its branch above rather than exiting.
            if (
                self.dropin_active.is_set()
                or self.chat_active.is_set()
                or self.wake_recording.is_set()
            ):
                continue
            if not woke:
                return
            self._emit_text({"type": "utterance_start", "trigger": "wake_word"})
            prefix: list[bytes] = []
            # Set when this iteration is following up on the bot's own
            # question (e.g., "did I get that right?"). Caps the
            # pre-speech wait so a non-replying user drops back to
            # wake-word listen quickly instead of holding the mic open
            # for the full max_record_seconds.
            pre_speech_timeout: float | None = None

            while not self.shutdown_event.is_set():
                self.response_done.clear()
                self.playback_active.clear()
                self.stop_playback.clear()
                # Cleared here so a stale set from a previous iteration
                # doesn't leak in. The receiver re-sets on response_end
                # if the next response is also expectant.
                self.expect_followup.clear()
                self._barge_prefix = []

                if not self._stream_capture(prefix, pre_speech_timeout_sec=pre_speech_timeout):
                    if self.shutdown_event.is_set():
                        return
                    # Follow-up timeout — user didn't reply. Drop back
                    # to wake-word listen instead of exiting the thread.
                    break

                outcome = self._await_response_with_barge(oww)
                if outcome == "done":
                    if self.expect_followup.is_set():
                        # Bot asked a question; capture the user's
                        # answer without requiring a fresh wake word.
                        log.info(
                            "expect_followup: capturing reply without "
                            "wake-word gate (pre_speech_timeout=%.1fs)",
                            self.cfg.followup_pre_speech_timeout,
                        )
                        self.expect_followup.clear()
                        self._emit_text(
                            {"type": "utterance_start", "trigger": "followup"}
                        )
                        prefix = []
                        pre_speech_timeout = self.cfg.followup_pre_speech_timeout
                        continue
                    break
                if outcome == "shutdown":
                    return
                # outcome == "barge": _barge_prefix holds the recent frames;
                # the inner loop runs again to capture the new utterance.
                # Barge-in is *not* a follow-up — clear the timeout so
                # the next capture uses the normal post-speech VAD logic.
                # If expect_followup was armed at the same time, the
                # server suppressed it (interrupted=true → flag dropped)
                # but the user's barge audio still routes — pending
                # confirmations parked in session context still resolve.
                if self.expect_followup.is_set():
                    log.info(
                        "barge-in fired while expect_followup was armed; "
                        "treating user's audio as a barge instead of a "
                        "wake-word-free reply. (Likely cause: speaker echo "
                        "during the bot's question. Raise "
                        "[barge_in] min_speech_ms or set "
                        "require_wake_word=true in config.)"
                    )
                prefix = self._barge_prefix
                pre_speech_timeout = None

    # ── WebSocket I/O ─────────────────────────────────────────────────

    async def _sender_loop(self) -> None:
        assert self.ws is not None and self.send_q is not None
        while True:
            kind, data = await self.send_q.get()
            try:
                if kind == "text":
                    await self.ws.send(data)
                else:
                    await self.ws.send(data)
            except ConnectionClosed:
                return

    async def _receiver_loop(self) -> None:
        assert self.ws is not None
        try:
            async for msg in self.ws:
                if isinstance(msg, str):
                    try:
                        payload = json.loads(msg)
                    except json.JSONDecodeError:
                        log.warning("non-JSON text frame: %r", msg[:200])
                        continue
                    self._handle_text_frame(payload)
                else:
                    # Binary — TTS audio chunk at the rate from response_start.
                    if not self.stop_playback.is_set():
                        self._response_audio_received.set()
                        if self._prebuffer_active:
                            # Hold this chunk in the prebuffer until the
                            # target accumulates (or response_end forces a
                            # flush). Releases all queued chunks at once
                            # when the target is met, so the playback
                            # thread starts with N seconds of cushion.
                            self._prebuffer_buffer.append(msg)
                            self._prebuffer_accumulated += len(msg)
                            if self._prebuffer_accumulated >= self._prebuffer_target_bytes:
                                self._flush_prebuffer()
                        else:
                            # During a drop-in, BOUND the playback backlog so
                            # call latency can't grow: if the consumer is
                            # behind, drop oldest queued audio to catch up
                            # (live audio prefers low latency to completeness).
                            if self.dropin_active.is_set():
                                while self.playback_q.qsize() > self._DROPIN_MAX_PLAYBACK_FRAMES:
                                    try:
                                        self.playback_q.get_nowait()
                                    except queue.Empty:
                                        break
                            self.playback_q.put((self.audio_sample_rate, msg))
        except ConnectionClosed:
            return

    def _handle_text_frame(self, payload: dict[str, Any]) -> None:
        t = payload.get("type")
        if t == "ready":
            log.info(
                "server ready: protocol=%s bot=%s",
                payload.get("protocol_version"),
                payload.get("bot_name"),
            )
            # A `ready` frame means the (possibly just-upgraded) code connected
            # and handshook cleanly — confirm the upgrade so the rollback
            # watchdog stands down, and clear the pending marker (Feature 10).
            self._upgrade_confirmed = True
            try:
                UPGRADE_PENDING_MARKER.unlink(missing_ok=True)
            except OSError as e:
                log.warning("upgrade: failed to clear pending marker: %s", e)
        elif t == "transcript":
            log.info("heard: %s", payload.get("text"))
        elif t == "response_start":
            self.audio_sample_rate = int(payload.get("audio_sample_rate") or 16_000)
            # TTS is about to play — kill music (and any still-playing wake
            # greeting) so they don't compete on the output device. Music
            # will only resume if the server sends a fresh music_start
            # after the response.
            self._stop_music()
            self._stop_greeting()
            self.playback_active.set()
            # Mark the device as "in use" the instant the response starts,
            # not when the playback thread eventually opens the stream
            # (~10-50 ms later). Otherwise a music_start frame arriving in
            # the same receiver-loop tick races the playback thread and
            # spawns mpg123 before TTS even begins.
            self._playback_idle.clear()
            self._response_audio_received.clear()
            self._post_playback_state = None
            # Arm the receiver-side prebuffer. Audio chunks for this
            # response will accumulate in `_prebuffer_buffer` until we
            # have ~tts_prebuffer_sec of audio (or response_end forces
            # an early flush for short responses).
            if self.cfg.tts_prebuffer_sec > 0:
                self._prebuffer_active = True
                self._prebuffer_buffer = []
                self._prebuffer_accumulated = 0
                self._prebuffer_target_bytes = int(
                    self.audio_sample_rate * 2 * self.cfg.tts_prebuffer_sec
                )
            self._leds.set_state("speaking")
            log.info(
                "%s [%s/%s]: %s",
                payload.get("matched_handler") or "qa",
                payload.get("matched_path"),
                "online" if payload.get("online") else "offline",
                payload.get("text"),
            )
        elif t == "response_end":
            # Force-flush any remaining prebuffer first — for short
            # responses the target was never reached, so we need to
            # release whatever's queued before the post-response cleanup
            # tries to wait on a stream that hasn't even started playing.
            if self._prebuffer_active:
                self._flush_prebuffer()
            # Set expect_followup BEFORE response_done so the mic thread
            # always observes both flags consistently — without this
            # ordering, the mic could wake on response_done, check
            # expect_followup before we set it, and miss the follow-up
            # signal.
            interrupted = bool(payload.get("interrupted"))
            if payload.get("expect_followup"):
                self.expect_followup.set()
                next_state = "listening"
                # Diagnostic: log every time the server asks for a
                # follow-up so we can correlate against the mic-thread
                # log line below ("expect_followup: capturing reply...").
                # If you see this fire but never see the capture log,
                # the response was interrupted (barge-in mid-question)
                # and the followup signal got dropped.
                log.info(
                    "expect_followup armed (response_end interrupted=%s)", interrupted,
                )
            else:
                next_state = "idle"

            # Decide whether to release the LED + response_done now or
            # defer until PortAudio has actually drained. The server
            # sends `response_end` the moment it finishes streaming bytes,
            # which is several hundred ms BEFORE the user hears the last
            # syllable. Releasing immediately makes the green "speaking"
            # LED disappear while audio is still coming out of the speaker.
            #
            # Defer when:
            #   * audio chunks were enqueued this turn (`_response_audio_received`)
            #   * we weren't interrupted (barge-in already drained the queue,
            #     so there's nothing to wait for, and the mic thread has
            #     already flipped to "listening" for the next capture)
            #
            # Stash next_state in `_post_playback_state` BEFORE clearing
            # `playback_active` — the playback thread reads it after
            # observing playback_active=False, and the GIL gives us a
            # happens-before chain through the two attribute writes.
            defer = self._response_audio_received.is_set() and not interrupted
            if defer:
                self._post_playback_state = next_state
                self.playback_active.clear()
                # response_done stays UNSET; close_stream will set it
                # along with the LED transition once the stream drains.
            else:
                self.playback_active.clear()
                if next_state == "listening":
                    self._leds.set_state("listening")
                else:
                    # If the mic thread already moved us to "listening" via
                    # barge-in, don't downgrade — the next capture is in progress.
                    self._leds.set_state_unless("listening", "idle")
                self.response_done.set()
            # Pi-local side-effect requested by the server (e.g.
            # WifiHandler asked us to reassociate after speaking
            # "OK, reconnecting now"). Run in a background thread that
            # waits for playback drain so the action only fires after
            # the user actually hears the response. Skipped on
            # interrupted=true: the bot's "OK, reconnecting now" got
            # cut off, so we never gave the user the heads-up and
            # shouldn't silently kick the WS.
            pi_action = payload.get("pi_action")
            if pi_action and not interrupted:
                pi_action_arg = payload.get("pi_action_arg")
                threading.Thread(
                    target=self._deferred_pi_action,
                    args=(str(pi_action), pi_action_arg),
                    daemon=True,
                    name=f"pi-action-{pi_action}",
                ).start()
            if interrupted:
                log.debug("response ended (interrupted)")
        elif t == "music_start":
            stream_url = payload.get("stream_url")
            if stream_url:
                # Defer to a worker thread so we can wait for any in-flight
                # TTS playback to drain (see _start_music_when_idle) without
                # blocking the asyncio receiver loop. The server emits
                # music_start immediately after response_end, but bytes from
                # the last TTS sentence are usually still in playback_q.
                threading.Thread(
                    target=self._start_music_when_idle,
                    args=(str(stream_url),),
                    daemon=True,
                    name="music-defer",
                ).start()
            else:
                log.warning("music_start missing stream_url")
        elif t == "music_stop":
            self._stop_music()
            # Music ended → drop the ring back to idle, unless a capture is
            # already in progress (don't clobber a "listening" the mic
            # thread just set).
            self._leds.set_state_unless("listening", "idle")
        elif t == "set_volume":
            # Master output volume (TTS + music). Apply on a worker thread
            # so the amixer subprocess doesn't block the asyncio receiver;
            # sent before response_start, so it lands just ahead of the
            # spoken confirmation, which then plays at the new level.
            level = payload.get("level")
            if level is not None:
                threading.Thread(
                    target=self._apply_output_volume,
                    args=(int(level),),
                    daemon=True,
                    name="set-volume",
                ).start()
        elif t == "sounds_changed":
            # The server re-rendered clips (a greeting was edited) — re-sync
            # the cache. We're on the event loop here (called from the async
            # receiver), so schedule the async sync as a task.
            asyncio.create_task(self._sync_sounds())
        elif t == "restart":
            # The server asked this satellite to restart its own service —
            # e.g. a config edit that only takes effect on a fresh process.
            # Run on a worker thread that drains any in-flight TTS playback
            # first (via _deferred_pi_action), so we don't cut a response
            # off mid-sentence before bouncing.
            log.info("restart requested by server")
            threading.Thread(
                target=self._deferred_pi_action,
                args=("restart", None),
                daemon=True,
                name="self-restart",
            ).start()
        elif t == "set_config":
            # The server pushed web-edited config. Merge into config.toml
            # (preserving comments), validate, back up, and restart to apply.
            # Run on a worker thread — it ends in a service restart.
            changes = payload.get("changes")
            if isinstance(changes, dict) and changes:
                log.info("set_config: %d change(s) from server", len(changes))
                threading.Thread(
                    target=self._apply_config_changes,
                    args=(dict(changes),),
                    daemon=True,
                    name="set-config",
                ).start()
            else:
                log.warning("set_config: no changes in payload; ignoring")
        elif t == "error":
            self._leds.set_state("error")
            log.error("server error: %s", payload.get("message"))
            # Treat error like a terminal response so the mic thread
            # unblocks and goes back to wake-word listen — without this,
            # the server can emit `error` (e.g. DB unreachable
            # during a turn) and we'd hang forever waiting for a
            # response_end that's never coming. Mirror what response_end
            # does: drain the playback queue, clear playback state, set
            # response_done so `_await_response_with_barge` returns, and
            # park the LED in "idle" rather than leaving it red. The LED
            # transition lets the next wake-word capture flip it back to
            # "listening" cleanly.
            self.stop_playback.set()
            self._drain_playback_q()
            self.playback_active.clear()
            self._post_playback_state = None
            self._leds.set_state_unless("listening", "idle")
            self.response_done.set()
        elif t == "upgrade":
            # The server asked this satellite to self-upgrade (Feature 10):
            # mirror its `satellite/` tree, then restart into the new code.
            # Run on a worker thread — it does blocking HTTP + a tarball
            # backup + a service restart and must not stall the event loop.
            log.info("upgrade requested by server")
            threading.Thread(
                target=self._apply_upgrade,
                args=(payload,),
                daemon=True,
                name="self-upgrade",
            ).start()
        elif t == "dropin_start":
            # Enter open-mic mode for a live two-way drop-in (Feature 4).
            self._enter_dropin(payload)
        elif t == "dropin_end":
            # Exit open-mic mode; the server sends a music_start after
            # this if the room had music suppressed.
            self._exit_dropin(payload)
        elif t == "chat_start":
            # Enter conversational chat mode (Feature #8): a Letta-backed
            # open-mic conversation. Sets the mic-thread state; the mic thread
            # runs `_chat_loop` on its next outer-loop tick.
            self._enter_chat(payload)
        elif t == "chat_end":
            # Exit conversational chat mode — the server sent this after an exit
            # phrase ("that's all", "stop") and the goodbye TTS. Clears the
            # mic-thread state so the loop drops back to wake-word listening.
            self._exit_chat(payload)
        elif t == "start_wake_recording":
            # Wake-word training (Feature #5): record N positive clips and
            # stream them to the server. Sets the mic-thread state; the
            # mic thread runs `_wake_recording_loop` on its next outer-loop tick.
            self._enter_wake_recording(payload)
        elif t == "stop_wake_recording":
            # Stop recording early. The mic thread's loop checks this Event each
            # frame and exits cleanly without emitting a partial clip.
            self.wake_recording.clear()
        elif t == "set_wake_word":
            # A trained model was pushed to this room — persist the slug,
            # mirror the model, and restart to load it. Run on a worker thread:
            # it does blocking HTTP + a service restart and must not stall the
            # asyncio receiver loop.
            slug = payload.get("slug")
            threading.Thread(
                target=self._apply_wake_switch,
                args=(slug, payload.get("threshold")),
                daemon=True,
                name="set-wake-word",
            ).start()
        elif t == "wake_models_changed":
            # A wake model was (re-)trained or removed — re-mirror the cache so
            # the local copy matches the server. Best-effort; scheduled
            # on the event loop since we're in the async receiver here.
            asyncio.create_task(asyncio.to_thread(self._sync_wake_models))
        elif t == "pong":
            pass
        else:
            log.debug("unknown text frame type=%r", t)

    async def _run_session(self) -> None:
        assert self._async_shutdown is not None
        url = self.cfg.domovoi_url.rstrip("/") + f"/v1/stream/{self.cfg.room_id}"
        log.info("connecting to %s", url)
        # Outer try/finally so `_on_session_ended` runs on EVERY exit
        # path — including when `websockets.connect` itself raises (e.g.,
        # "timed out during opening handshake") before the inner block
        # is reached. An earlier draft only ran the cleanup inside the
        # inner finally, which left the mic thread stuck on
        # response_done if the handshake failed while an utterance was
        # in flight.
        try:
            async with websockets.connect(url, max_size=2**24) as ws:
                self.ws = ws
                self.send_q = asyncio.Queue()
                await ws.send(json.dumps({
                    "type": "hello",
                    "room_id": self.cfg.room_id,
                    # The EFFECTIVE wake word — the sidecar slug a dashboard
                    # push installed, else the [wake] config — so the
                    # server's per-room view matches what we listen for.
                    "wake_word": _effective_wake_word(self.cfg),
                    # Version LABEL of the last applied self-upgrade (Feature
                    # 10), so the dashboard can show which code this room runs.
                    # None until the first upgrade lands. Supersedes the old
                    # hard-coded client_version.
                    "synced_sha": _read_synced_sha(),
                    # Whether this board has on-chip AEC (full duplex), so the
                    # server can gate drop-in / open-mic modes per room.
                    "supports_full_duplex": self.cfg.device.supports_full_duplex,
                    # Per-device pairing token (V002 WS auth). Generated on
                    # first boot; the server binds this room to its sha256 on
                    # first sight (trust-on-first-use) and refuses a later
                    # mismatch. None only if the sidecar couldn't be read/written
                    # (degrades to a tokenless older-style hello).
                    "pairing_token": _effective_pairing_token(),
                }))
                # WS is back up. Mark the disconnect window closed and
                # clear the degraded flag — the watcher will re-arm if
                # rate is still bad on its next tick. Also fire one
                # initial wifi_status push so the server's cache
                # has a reading for "how's your wifi?" right away,
                # rather than waiting up to a full poll interval.
                self._ws_disconnected_since = None
                if self._network_degraded.is_set():
                    log.info("WS reconnected; clearing network_degraded flag")
                    self._network_degraded.clear()
                if self.cfg.wifi_enabled:
                    link = self._check_wifi_link()
                    if link is not None:
                        self._emit_wifi_status(link)
                # Report our current hardware output volume so the
                # server's per-room cache seeds correctly and relative
                # "turn it up / down" bumps start from the real level.
                vol = self._read_output_volume()
                if vol is not None:
                    self._emit_volume_status(vol)
                # Report which voice we speak in so the server renders
                # this room's responses + greetings in it.
                self._emit_voice_status()
                # Report current config so the dashboard's per-satellite
                # Settings tab can show + edit real values.
                self._emit_config_status()
                # Pull any updated sound clips (greetings / canned) from the
                # server into the local cache. Best-effort — falls back
                # to cached/bundled clips on any failure. Scoped to our voice
                # so the cache holds this satellite's voice clips.
                await self._sync_sounds()

                sender = asyncio.create_task(self._sender_loop(), name="ws-sender")
                receiver = asyncio.create_task(self._receiver_loop(), name="ws-receiver")
                shutdown_watch = asyncio.create_task(
                    self._async_shutdown.wait(), name="shutdown-watch"
                )
                try:
                    done, pending = await asyncio.wait(
                        {sender, receiver, shutdown_watch},
                        return_when=asyncio.FIRST_COMPLETED,
                    )
                    for t in pending:
                        t.cancel()
                finally:
                    self.ws = None
        finally:
            self._on_session_ended()

    def _on_session_ended(self) -> None:
        """Wake any thread waiting on a response that's not coming.

        The mic thread blocks in `_await_response_with_barge` waiting for
        `response_done` to flip — set on `response_end`. If the WS drops
        mid-utterance or mid-response, the server never sends
        `response_end`, so without this signal the mic thread sits
        consuming audio frames without feeding them to the wake-word
        predictor — wake word silently stops working until the process
        restarts. Setting `response_done` here lets the wait return
        "done", the inner loop break, and the outer loop drop back to
        `_wait_for_wake` so the next reconnect resumes normal operation.

        Also drains pending TTS playback (a half-cut response is worse
        than silence) and resets the LED to idle (otherwise it'd stay
        "speaking" or "thinking" indefinitely).
        """
        log.info("session ended; signaling mic thread to drop back to wake-word listen")
        self.response_done.set()
        self.playback_active.clear()
        self.stop_playback.set()
        self._drain_playback_q()
        # Best-effort: a wake-clip recording (Feature #5) is server-driven, so
        # a dropped WS means no more frames will be consumed by the server.
        # Clear the state so the mic thread leaves `_wake_recording_loop` and
        # drops back to wake-word listen on reconnect (the dashboard can
        # re-start recording once the room is back).
        if self.wake_recording.is_set():
            self.wake_recording.clear()
            self._wake_rec_params = None
        # A dropped WS ends any open-mic sub-mode. The server re-derives mode on
        # reconnect (a fresh session has no conversational_mode), so a Pi that
        # kept chat_active / dropin_active would be stuck streaming a
        # wake-word-less mic the server now treats as command turns. Drop both
        # so the mic thread falls back to the wake loop on reconnect.
        if self.chat_active.is_set():
            self.chat_active.clear()
        if self.dropin_active.is_set():
            self.dropin_active.clear()
        # Squash any deferred post-response LED state — we're forcing
        # idle here, and don't want close_stream to overwrite it back to
        # "listening" once the (now-drained) stream closes.
        self._post_playback_state = None
        # Mark the disconnect for the wifi watcher's degraded-mode
        # decision. Only the *first* disconnect in a streak counts —
        # if _on_session_ended runs again on a subsequent failed
        # reconnect, we want the original timestamp so the elapsed
        # window measures the whole outage, not just the latest leg.
        if self._ws_disconnected_since is None:
            self._ws_disconnected_since = time.monotonic()
        try:
            self._leds.set_state("idle")
        except Exception:
            pass

    async def run(self) -> None:
        self.loop = asyncio.get_running_loop()
        self._async_shutdown = asyncio.Event()

        # Self-upgrade rollback (Feature 10): as early as practical, check for a
        # pending upgrade and arm the watchdog so a wedged new build rolls back
        # before we even open the mic / connect.
        self._arm_upgrade_watchdog()

        log.info("device profile: %s (%s)", self.cfg.device.name, self.cfg.device.description)
        if self.cfg.tts_playback_gain != 1.0:
            log.info("TTS playback gain: %.2fx (hard-clipped)", self.cfg.tts_playback_gain)
        # The XVF3800's on-chip AEC needs the playback signal as its echo
        # reference, which only happens if TTS plays back THROUGH the array
        # (its own speaker jack). If output_device is left at the system
        # default it'll likely route elsewhere (HDMI / Pi audio) and AEC has
        # nothing to cancel — barge-in then false-triggers on speaker echo.
        if self.cfg.device.playback_sample_rate is not None and self.cfg.output_device is None:
            log.warning(
                "device profile %r expects playback through the array for "
                "on-chip AEC, but [audio] output_device is unset (system "
                "default). Pin output_device to the XVF3800 (see "
                "--list-devices / PROVISIONING) or barge-in may misfire on "
                "speaker echo.",
                self.cfg.device.name,
            )

        self._leds.start()
        self._start_mic()
        self._playback_thread = threading.Thread(
            target=self._playback_thread_run, daemon=True, name="playback"
        )
        self._playback_thread.start()
        self._mic_thread = threading.Thread(
            target=self._mic_thread_run, daemon=True, name="mic"
        )
        self._mic_thread.start()
        # WiFi self-heal watcher — polls rx bitrate + reassociates when
        # the link wedges. Daemon so a misbehaving iw/wpa_cli can't
        # block process shutdown. See `_wifi_watcher_thread_run`.
        if self.cfg.wifi_enabled:
            self._wifi_thread = threading.Thread(
                target=self._wifi_watcher_thread_run, daemon=True, name="wifi-watcher"
            )
            self._wifi_thread.start()

        try:
            backoff = 1.0
            while not self.shutdown_event.is_set():
                try:
                    await self._run_session()
                    backoff = 1.0
                except (OSError, websockets.WebSocketException) as e:
                    log.warning("connection lost: %s", e)
                if self.shutdown_event.is_set():
                    break
                log.info("reconnecting in %.1fs", backoff)
                try:
                    # Wait either for the backoff to elapse or for shutdown
                    # to be requested — whichever comes first.
                    await asyncio.wait_for(self._async_shutdown.wait(), timeout=backoff)
                    break  # shutdown fired during the backoff wait
                except asyncio.TimeoutError:
                    pass  # backoff elapsed, retry the connection
                except asyncio.CancelledError:
                    break
                backoff = min(backoff * 2, 30.0)
        finally:
            self.shutdown_event.set()
            self._stop_music()
            self._stop_greeting()
            self._stop_mic()
            if self._mic_thread is not None:
                self._mic_thread.join(timeout=2.0)
            if self._playback_thread is not None:
                self._playback_thread.join(timeout=2.0)
            if self._wifi_thread is not None:
                self._wifi_thread.join(timeout=2.0)
            self._leds.stop()


