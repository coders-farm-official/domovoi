def _ensure_config(path: Path) -> bool:
    """If config doesn't exist, write the example next to it. Returns True if the
    config exists (was already there or freshly written; in the latter case we
    still want the user to edit before running)."""
    if path.exists():
        return True
    example = Path(__file__).resolve().parent / "config.toml.example"
    path.parent.mkdir(parents=True, exist_ok=True)
    if example.exists():
        shutil.copy(example, path)
        print(f"Wrote example config to {path}. Edit it (room_id, domovoi_url) then re-run.", file=sys.stderr)
    else:
        print(f"No config at {path} and no template found at {example}.", file=sys.stderr)
    return False


def _list_devices() -> None:
    print(sd.query_devices())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Pi satellite client for the Domovoi voice assistant.")
    parser.add_argument("--config", type=Path, default=CONFIG_PATH, help=f"Config file (default: {CONFIG_PATH})")
    parser.add_argument("--list-devices", action="store_true", help="Print sounddevice IDs and exit.")
    parser.add_argument("--input-device", type=int, default=None, help="Override input_device from config.")
    parser.add_argument("--output-device", type=int, default=None, help="Override output_device from config.")
    args = parser.parse_args(argv)

    if args.list_devices:
        _list_devices()
        return 0

    if not _ensure_config(args.config):
        return 2

    cfg = Config.load(args.config)
    if args.input_device is not None:
        cfg.input_device = args.input_device
    if args.output_device is not None:
        cfg.output_device = args.output_device

    logging.basicConfig(
        level=cfg.log_level,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )

    sat = Satellite(cfg)

    def _on_signal(*_: Any) -> None:
        log.info("shutdown requested")
        sat.shutdown_event.set()
        # The threading event is enough for the worker threads, but the
        # asyncio side is sleeping inside `await ws.recv()` / `wait_for(...)`.
        # Poke an asyncio event from the signal-handler thread so those
        # awaits can complete promptly without waiting on a network round-trip.
        if sat.loop is not None and sat._async_shutdown is not None:
            sat.loop.call_soon_threadsafe(sat._async_shutdown.set)

    for s in (signal.SIGINT, signal.SIGTERM):
        try:
            signal.signal(s, _on_signal)
        except (ValueError, OSError):
            pass  # not on the main thread / not supported

    try:
        asyncio.run(sat.run())
    except KeyboardInterrupt:
        sat.shutdown_event.set()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
