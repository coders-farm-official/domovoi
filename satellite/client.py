def _read_synced_sha() -> str | None:
    """The version label of the last applied upgrade, read from the sidecar.
    None when no upgrade has ever landed (or the sidecar is unreadable)."""
    try:
        if SYNCED_SHA_SIDECAR.is_file():
            sha = SYNCED_SHA_SIDECAR.read_text(encoding="utf-8").strip()
            if sha:
                return sha
    except OSError:
        pass
    return None


def _effective_pairing_token() -> str | None:
    """This satellite's WS pairing token (V002), generated on first boot.

    Reads ``PAIRING_TOKEN_SIDECAR`` if present; otherwise generates a fresh
    ``secrets.token_hex(32)`` (256-bit), writes it (best-effort chmod 0o600),
    and returns it. A filesystem error is non-fatal — we return whatever we
    have (possibly None), so a read-only config dir degrades to a tokenless
    (older-protocol) hello rather than crashing the client. The value is sent as the
    hello frame's ``pairing_token``; the server binds the room to its sha256
    on first sight and refuses any later mismatch."""
    try:
        if PAIRING_TOKEN_SIDECAR.is_file():
            tok = PAIRING_TOKEN_SIDECAR.read_text(encoding="utf-8").strip()
            if tok:
                return tok
    except OSError as e:
        log.warning("pairing: could not read token sidecar: %s", e)
        return None
    # Absent (or empty) — generate + persist a new one.
    token = secrets.token_hex(32)
    try:
        CONFIG_DIR.mkdir(parents=True, exist_ok=True)
        PAIRING_TOKEN_SIDECAR.write_text(token + "\n", encoding="utf-8")
        try:
            PAIRING_TOKEN_SIDECAR.chmod(0o600)
        except OSError:
            # chmod is a no-op / unsupported on some filesystems (Windows,
            # certain SD-card mounts) — the token is still written.
            pass
        log.info("pairing: generated a new pairing token (first boot)")
    except OSError as e:
        log.warning("pairing: could not write token sidecar: %s", e)
        return None
    return token


def _effective_voice(cfg: "Config") -> str | None:
    """The voice this satellite should speak in: the runtime sidecar
    selection if present, else the configured ``[voice] name``, else None
    (→ the server's default voice)."""
    try:
        if VOICE_SIDECAR.is_file():
            name = VOICE_SIDECAR.read_text(encoding="utf-8").strip()
            if name:
                return name
    except OSError:
        pass
    return cfg.voice_name


def _effective_wake_word(cfg: "Config") -> str:
    """The wake word this satellite should listen for: the runtime sidecar
    slug if present (a model pushed from the dashboard), else the configured
    ``[wake] wake_word``. The openWakeWord prediction dict is keyed by the
    loaded model's STEM, so this value MUST equal the stem of whatever model
    `_effective_wake_model_path` loads — both derive from the same sidecar
    slug. Mirrors `_effective_voice`."""
    try:
        if WAKE_SIDECAR.is_file():
            slug = WAKE_SIDECAR.read_text(encoding="utf-8").strip()
            if slug:
                return slug
    except OSError:
        pass
    return cfg.wake_word


def _effective_wake_model_path(cfg: "Config") -> str | None:
    """The custom wake-model file to load: the sidecar slug's mirrored
    ``<slug>.onnx`` under WAKE_MODELS_DIR if both the sidecar is set AND that
    file exists, else the configured ``[wake] wake_word_model_path``, else
    None (→ openWakeWord loads the named built-in). Returns a str path (the
    openWakeWord loader takes a path string). Mirrors `_effective_voice`'s
    precedence: a dashboard-pushed model overrides the TOML."""
    try:
        if WAKE_SIDECAR.is_file():
            slug = WAKE_SIDECAR.read_text(encoding="utf-8").strip()
            if slug:
                model = WAKE_MODELS_DIR / f"{slug}.onnx"
                if model.is_file():
                    return str(model)
    except OSError:
        pass
    if cfg.wake_word_model_path and cfg.wake_word_model_path.exists():
        return str(cfg.wake_word_model_path)
    return None


def _effective_wake_threshold(cfg: "Config") -> float:
    """The detection threshold to compare openWakeWord scores against: the
    per-word threshold pushed with a dashboard model (WAKE_THRESHOLD_SIDECAR)
    if present + parseable, else the configured ``[wake] threshold``. So a
    registry word's tuned sensitivity rides along with its pushed model."""
    try:
        if WAKE_THRESHOLD_SIDECAR.is_file():
            raw = WAKE_THRESHOLD_SIDECAR.read_text(encoding="utf-8").strip()
            if raw:
                return float(raw)
    except (OSError, ValueError):
        pass
    return cfg.wake_threshold


def _resolve_sound(relpath: str) -> Path:
    """A single clip path — the synced cache copy if present, else bundled."""
    cached = SOUNDS_CACHE_DIR / relpath
